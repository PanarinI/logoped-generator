let APP_V = null;

async function checkVersion() {
  let v = '';
  try {
    const r = await fetch('/api/version', { cache: 'no-store' });
    v = (await r.json()).v || '';
  } catch (e) { return; }            // сеть моргнула — молчим, не мешаем работать
  if (!v) return;
  if (APP_V === null) { APP_V = v; return; }
  if (v === APP_V) return;
  const box = $('new-version');
  if (!S.edited) { location.reload(); return; }
  if (box) box.hidden = false;
}

