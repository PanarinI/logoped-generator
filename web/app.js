const OTZYV_KEY = 'lz.saves';
const OTZYV_ASKED = 'lz.asked';
let sheetsGot = 0;              // запасной счётчик, когда хранилище закрыто

function lsGet(key) {
  try { return window.localStorage.getItem(key); } catch (e) { return null; }
}
function lsSet(key, value) {
  try { window.localStorage.setItem(key, value); } catch (e) { /* закрыто — не беда */ }
}

/* Контекст отзыва. Без него отзыв нечитаем: «мало материала» на [Щ] и на [С] —
   это разные новости, а «оформление» на лабиринте и на дорожке — разные места. */
function otzyvContext() {
  return {
    sound: S.sound || '',
    material: S.tab || '',
    profile: [...(S.profile || [])].join(','),
    saves: sheetsGot,
  };
}

async function sendOtzyv(body) {
  try {
    await fetch('/api/otzyv', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(Object.assign(otzyvContext(), body)),
    });
    return true;
  } catch (e) {
    return false;
  }
}

/* Лист получен — скачан или отправлен на печать. Для человека это одно
   событие: у него на руках материал. */
function gotSheet() {
  sheetsGot = (parseInt(lsGet(OTZYV_KEY), 10) || 0) + 1;
  lsSet(OTZYV_KEY, String(sheetsGot));
  if (sheetsGot >= 2 && !lsGet(OTZYV_ASKED)) {
    // Пауза не для красоты: сразу после клика на экране появляется диалог
    // сохранения файла, и полоса ушла бы под него незамеченной.
    setTimeout(showAskBar, 1200);
  }
}

function showAskBar() {
  const bar = $('ask-bar');
  if (!bar || !bar.hidden) return;
  if (lsGet(OTZYV_ASKED)) return;
  bar.hidden = false;
}

function closeAskBar(remember) {
  const bar = $('ask-bar');
  if (bar) bar.hidden = true;
  if (remember) lsSet(OTZYV_ASKED, '1');
}

function askThanks(text) {
  const bar = $('ask-bar');
  if (!bar) return;
  bar.innerHTML = '<p class="ask-done">' + text + '</p>';
  lsSet(OTZYV_ASKED, '1');
  setTimeout(() => { bar.hidden = true; }, 2600);
}

function bindOtzyv() {
  const open = $('otzyv-open');
  const win = $('otzyv-win');
  const back = $('otzyv-back');
  const area = $('otzyv-text');

  const closeWin = () => {
    win.hidden = true;
    back.hidden = true;
  };

  if (open) {
    open.onclick = () => {
      win.hidden = false;
      back.hidden = false;
      area.focus();
    };
  }
  if (back) back.onclick = closeWin;
  if ($('otzyv-cancel')) $('otzyv-cancel').onclick = closeWin;
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && win && !win.hidden) closeWin();
  });

  if ($('otzyv-send')) {
    $('otzyv-send').onclick = async () => {
      const text = (area.value || '').trim();
      if (!text) { area.focus(); return; }
      const btn = $('otzyv-send');
      btn.disabled = true;
      btn.textContent = 'Отправляем…';
      await sendOtzyv({ text, contact: ($('otzyv-contact').value || '').trim() });
      // «Спасибо» показываем всегда: если письмо не дошло по сети, виноват не
      // человек, и сообщать ему об этом нечестно — он уже сделал свою часть.
      win.innerHTML = '<h2>Спасибо</h2><p class="hint">Прочитаю всё. '
                    + 'Если оставили контакт — отвечу.</p>';
      setTimeout(closeWin, 2200);
    };
  }

  const bar = $('ask-bar');
  if (!bar) return;

  if ($('ask-close')) $('ask-close').onclick = () => closeAskBar(true);

  const chosen = new Set();
  const reasons = $('ask-reasons');
  if (reasons) {
    reasons.onclick = (e) => {
      const b = e.target.closest('button[data-r]');
      if (!b) return;
      const key = b.dataset.r;
      if (chosen.has(key)) { chosen.delete(key); b.classList.remove('is-on'); }
      else { chosen.add(key); b.classList.add('is-on'); }
    };
  }

  /* РЕЙТБАР. ⚠ 08-26: здесь стояли «Да/Нет» на вопрос «дадите этот лист
     ребёнку?». Слово автора: формулировка грубая. Она и правда ставит человека
     перед приговором о собственной работе, а сказать «нет» про свой же выбор
     неловко — значит и ответы кривые. Оценка звёздами не требует признания.

     ⚡ ОДНА ЗАПИСЬ, А НЕ ДВЕ. Соблазн был отправить оценку сразу по нажатию
     звезды, а текст — второй посылкой. Так уже сделано у «Нет», и STATE уже
     держит предупреждение: тот ответ приходит ДВУМЯ записями и читается
     неверно. Поэтому звезда только запоминается и открывает поле, а уходит
     всё вместе — по «Отправить» или при закрытии полосы. Ничего не теряется:
     закрытие тоже отправляет. */
  let stars = 0;
  let sent = false;
  const starsBox = $('ask-stars');

  function paint(n) {
    [...starsBox.children].forEach((b, i) => {
      b.classList.toggle('is-lit', i < n);
      b.textContent = i < n ? '\u2605' : '\u2606';
    });
  }

  if (starsBox) {
    for (let n = 1; n <= 5; n += 1) {
      const b = el('button', 'ask-star', '\u2606');
      b.type = 'button';
      b.setAttribute('aria-label', n + ' из 5');
      b.onmouseenter = () => paint(n);
      b.onfocus = () => paint(n);
      b.onclick = () => {
        stars = n;
        paint(n);
        // Поле — продолжение, а не условие: оценка уже сказана.
        $('ask-q').textContent = 'Спасибо. Если есть время — что поправить?';
        $('ask-why').hidden = false;
      };
      starsBox.appendChild(b);
    }
    starsBox.onmouseleave = () => paint(stars);
  }

  async function flushAsk() {
    if (sent || !stars) return;
    sent = true;
    await sendOtzyv({
      stars: stars,
      reasons: [...chosen],
      text: (($('ask-text') || {}).value || '').trim(),
    });
  }

  if ($('ask-send')) {
    $('ask-send').onclick = async () => {
      const btn = $('ask-send');
      btn.disabled = true;
      btn.textContent = 'Отправляем…';
      await flushAsk();
      // ⚠ 08-26, слово автора: после отправки — коротко «Спасибо!». Длинная
      // благодарность после уже сделанного дела читается как самолюбование.
      askThanks('Спасибо!');
    };
  }
  // Закрыли, не дописав, — оценка всё равно уходит: она уже поставлена.
  if ($('ask-close')) {
    $('ask-close').onclick = () => { flushAsk(); closeAskBar(true); };
  }
}

