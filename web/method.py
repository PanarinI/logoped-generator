def as_json() -> Dict[str, Any]:
    """Справка по всем вкладкам сразу — интерфейс покажет нужную."""
    def pack(rules):
        return [{"tier": t, "tier_label": TIER_LABEL[t], "text": x, "source": s}
                for t, x, s in rules]

    return {
        "tiers": [{"tier": t, "label": l} for t, l in TIER_LABEL.items()],
        "by_tab": {
            tab: {"title": sec["title"],
                  "sections": [{"num": "", "title": g["title"],
                                "rules": pack(g["rules"])}
                               for g in sec["groups"]]}
            for tab, sec in SECTIONS.items()
        },
    }
