def as_json() -> Dict[str, Any]:
    """Цепочка целиком — для панели «Показать методику»."""
    def pack(rules):
        return [{"tier": t, "tier_label": TIER_LABEL[t], "text": x, "source": s}
                for t, x, s in rules]

    return {
        "tiers": [{"tier": t, "label": l} for t, l in TIER_LABEL.items()],
        "sections": (
            [{"num": "", "title": FOUNDATION["title"], "rules": pack(FOUNDATION["rules"])},
             {"num": "", "title": FILTER["title"], "rules": pack(FILTER["rules"])}]
            + [{"num": b["num"], "title": b["title"], "rules": pack(b["rules"])}
               for b in BLOCKS]
            + [{"num": "", "title": FRAME["title"], "rules": pack(FRAME["rules"])}]
        ),
    }


def counts() -> Dict[str, int]:
    """Сколько чего — чтобы логопед сразу видел долю нашего."""
    out = {T_BOOK: 0, T_CALC: 0, T_OURS: 0, T_OPEN: 0}
    for sec in as_json()["sections"]:
        for r in sec["rules"]:
            out[r["tier"]] = out.get(r["tier"], 0) + 1
    return out
