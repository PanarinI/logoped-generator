# -*- coding: utf-8 -*-
"""
human.py — ПЕРЕВОД С НАШЕГО ЯЗЫКА НА ЧЕЛОВЕЧЕСКИЙ.

Зачем. Движок говорит честно, но по-своему: «канон правило 11: слоговой материал
28 мм > ¼ словесного (107 мм) — сократите слоги». Всё это правда, но логопед
миллиметрами ничего не меряет, номеров блоков не знает и слова purity_scope
никогда не видел. Такой текст на экране — не честность, а неуважение.

Закон (автор, 2026-08-04): на экране не должно быть ни одного слова, которое
существует только у нас в коде и в переписке.

Что делает модуль: сворачивает 88 разных машинных строк в короткий список
человеческих сообщений. Каждое отвечает на два вопроса — ЧТО случилось и ЧТО
делать. Внутренние тексты не пропадают: они уходят в поле `raw` ответа, чтобы
разработчик мог посмотреть, но на экран не попадают.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Tuple

# Человеческие имена звуков для подстановки в текст
PH_LABEL = {
    "л": "Л", "л'": "Ль", "р": "Р", "р'": "Рь", "с": "С", "с'": "Сь",
    "з": "З", "з'": "Зь", "ц": "Ц", "ш": "Ш", "ж": "Ж", "щ": "Щ", "ч": "Ч",
    "й": "Й", "к": "К", "к'": "Кь", "г": "Г", "г'": "Гь", "х": "Х", "х'": "Хь",
}

BLOCK = "блок"    # печатать нельзя
NOTE = "заметка"  # к сведению


def _phonemes(text: str) -> List[str]:
    """Вытащить звуки из машинной строки вида «(л) · «Маляр» (л')»."""
    out: List[str] = []
    for m in re.finditer(r"\(([^)]{1,24})\)", text):
        for part in m.group(1).split(","):
            p = part.strip()
            if p in PH_LABEL and PH_LABEL[p] not in out:
                out.append(PH_LABEL[p])
    return out


# ── ПРАВИЛА ПЕРЕВОДА ───────────────────────────────────────────────────
# Порядок важен: первое совпавшее правило выигрывает.
# Каждое правило: (регулярка, вид, функция-текст).

# ⚠ Числа канона здесь НЕТ намеренно. Канон блока [4] зависит от типа слога —
# на прямых слогах это 12, на стечениях 7 (`content.canon_min_words`). Вшитая
# двенадцатка печатала логопеду неправду: на стечении лист с восемью словами
# нормален, а экран писал «мало, обычно берут от 12».
# Настоящее число уже приходит в самой машинной строке («меньше канонического
# минимума 7», «норма 7-16») — читаем его оттуда, а не держим свою копию.
# Один факт — один дом.


def _num(m: re.Match) -> int:
    """Первая непустая группа-число. Регулярки с альтернативами дают None."""
    for g in m.groups():
        if g and str(g).isdigit():
            return int(g)
    return -1


def _two_nums(m: re.Match) -> Tuple[int, int]:
    """Сколько нашлось и сколько нужно. Второго числа нет → (n, -1)."""
    nums = [int(g) for g in m.groups() if g and str(g).isdigit()]
    if not nums:
        return -1, -1
    return nums[0], (nums[1] if len(nums) > 1 else -1)


def _few_words(m: re.Match, text: str) -> str:
    n, need = _two_nums(m)
    if need < 0:
        # Строка без числа канона — сказать точно нечего, а врать нельзя.
        return ""
    if n >= need:
        # Норма. «Нашлось 15 из 16» не проблема, а деталь сборки: логопеду
        # показывать нечего.
        return ""
    return (f"Слов для этого листа нашлось мало — {n}. Нужно от {need}: "
            f"меньше — ребёнку не на чем закрепить звук. "
            f"Снимите один звук справа или возьмите другой слог.")


def _syllables_outweigh(m: re.Match, text: str) -> str:
    return ("Слогов на листе получилось больше, чем слов. Для занятия это "
            "перекос: слоги — разминка, а закрепляется звук на словах.")


def _few_syllables(m: re.Match, text: str) -> str:
    return ("Слоговых рядов вышло меньше обычного — слов не хватило, чтобы "
            "каждый ряд закончился словом.")


def _did_not_fit(m: re.Match, text: str) -> str:
    """Говорим ТОЛЬКО о том, на что логопед может ответить действием.

    Снятые предложения — повод сменить тип слога, это рычаг. А «часть слов
    пришлось снять» рычага не даёт: лист виден целиком на экране, и сообщение
    лишь отнимает внимание у профиля и самого листа. Снято 08-09 по слову
    автора. След остаётся в `raw` — для нас, не для экрана.
    """
    if "блок [6]" in text or "предложения" in text:
        return ("Предложения на страницу не поместились и сняты. Попробуйте "
                "другой тип слога — материал будет короче.")
    return ""


def _no_column(m: re.Match, text: str) -> str:
    syl = m.group(1).strip().rstrip(":")
    return (f"Для слога «{syl}» подходящих слов не нашлось — "
            f"эта колонка на листе пустая.")


def _no_game(m: re.Match, text: str) -> str:
    return ("Игру собрать не из чего: на этом наборе слов не набирается "
            "четырёх примеров. Блок с игрой на листе пропущен.")


def _no_chant(m: re.Match, text: str) -> str:
    return ("Чистоговорку составить не удалось: среди слов нет такого, на "
            "которое рифмуется слог. Блок пропущен.")


def _no_sentence(m: re.Match, text: str) -> str:
    return ("Часть предложений собрать не удалось — подходящих слов мало.")


def _few_sentences(m: re.Match, text: str) -> str:
    n = _num(m)
    return (f"Предложений получилось {n} — меньше обычных шести."
            if n > 0 else "Предложений получилось меньше обычного.")


def _dirty_names(m: re.Match, text: str) -> str:
    """Названия упражнений и звукообраз — их читает ВЗРОСЛЫЙ, не ребёнок.

    ⛔ Здесь стоял текст «звуки, которые ребёнку пока трудны». Это было враньё:
    профиль ребёнка логопед мог вообще не вводить, а движок всё равно убирает
    звуки, СМЕШИВАЕМЫЕ с целевым, — это методическое правило, а не знание про
    конкретного ребёнка. Приписывать ребёнку то, чего мы про него не знаем,
    нельзя (поймано автором 08-06).

    Вдобавок само сообщение избыточно: логопед видит слово «Лошадка» и без нас
    знает, что там [л]. Поэтому оно теперь показывается ТОЛЬКО когда профиль
    ребёнка реально задан и пересекается с названиями, — см. RULES ниже.
    """
    ph = _phonemes(text)
    kak = ", ".join(ph) if ph else "звуки не из этого листа"
    where = "названиях упражнений" if "упражнений" in text else "подсказке к звуку"
    return (f"В {where} есть {kak} — их читает взрослый, ребёнок не повторяет. "
            f"Если у ребёнка эти звуки не поставлены, замените упражнение своим.")


def _fused(m: re.Match, text: str) -> str:
    pair = m.group(1) if m.lastindex else ""
    p = f" «{pair}»" if pair else ""
    return (f"Часть слоговых рядов убрана: сочетание{p} при чтении вслух "
            f"сливается в другой звук. Слова с ним на листе остались — в "
            f"словах оно звучит правильно.")


def _nothing_at_all(m: re.Match, text: str) -> str:
    return ("Для такого набора звуков чистых слов не осталось совсем. "
            "Снимите один звук справа или возьмите другой тип слога — "
            "подмешивать слова с трудными звуками генератор не станет.")


# ⚠ 2026-08-09, по разбору автора. Из таблицы СНЯТЫ два правила, и это
# осознанно, а не потеряно:
#   • «правило 11» (слогов больше, чем слов) — внутренняя проверка канона.
#     Логопеду она не даёт ни решения, ни рычага; её место в панели методики;
#   • «в названиях упражнений есть Ч, Ж, С» — следствие границы purity_scope
#     (названия читает взрослый). Тоже объяснение, а не действие.
# Обе строки продолжают приходить из движка и лежат в `raw`: мы их видим,
# логопед — нет. Экран логопеда держит в фокусе профиль и лист.
RULES: List[Tuple[re.Pattern, str, Any]] = [
    (re.compile(r"чистых слов нет вообще|нашлось 0 слов"), BLOCK, _nothing_at_all),
    # Обе строки движка несут ОБА числа — сколько нашлось и сколько нужно:
    # «канон [4]: слов 8, норма 7-16» и «слов 8 — меньше канонического минимума 7».
    (re.compile(r"канон \[4\]: слов (\d+), норма (\d+)"), BLOCK, _few_words),
    (re.compile(r"слов (\d+) — меньше канонического минимума (\d+)"), BLOCK, _few_words),
    (re.compile(r"нашлось (\d+) слов из (\d+)"), NOTE, _few_words),
    (re.compile(r"канон \[3\]|слогов \d+ — меньше канонических"), NOTE, _few_syllables),
    (re.compile(r"НЕ ВЛЕЗАЛО|не влезало"), NOTE, _did_not_fit),
    (re.compile(r"колонки «([^»]+)» нет"), NOTE, _no_column),
    (re.compile(r"блок \[5\] пуст"), NOTE, _no_game),
    (re.compile(r"чистоговорка не построена"), NOTE, _no_chant),
    (re.compile(r"предложение из \d+ слов не собрано"), NOTE, _no_sentence),
    (re.compile(r"канон \[6\]: предложений (\d+)|предложений (\d+) — меньше"), NOTE, _few_sentences),
    (re.compile(r"слоговые ряды сняты.*«([^»]+)»"), NOTE, _fused),
]


# ── ПОЧЕМУ МАТЕРИАЛ НЕ ДЕЛАЕТ ТАКОЙ СЛОГ ───────────────────────────────
# Коды приходят из `logoped_slovar/capabilities.py`; фраза живёт здесь, чтобы
# у слова, которое читает логопед, был один дом (локальный закон 3).
# Родилось 08-10: на КЛА слоговая дорожка отказывалась фразой со словом
# «cluster_onset», а звуковая молча подменяла слог на прямой.

MATERIAL_NAME = {
    "sheet": "лист",
    "track": "слоговая дорожка",
    "propisi": "звуковая дорожка",
}

# Винительный падеж — для фразы «собрать …».
MATERIAL_VIN = {
    "sheet": "лист",
    "track": "слоговую дорожку",
    "propisi": "звуковую дорожку",
}


def why_syllable(reason: str, syllable: str = "", material: str = "") -> str:
    """Человеческая причина отказа по типу слога. Пусто = причины нет."""
    syl = f"«{syllable.upper()}»" if syllable and syllable != "—" else "такой слог"
    thing = MATERIAL_NAME.get(material, "материал")
    # ⚠ 2026-08-23. Тексты были втрое длиннее: они писались для ХОВЕРА, где
    # объём ничего не стоит. Когда причины вышли на экран, четыре таких абзаца
    # подряд превратили панель в стену — слово автора: «нахуя эта проза». На
    # экране причина обязана читаться за один взгляд: одна фраза, суть впереди.
    # Подробности ушли в «Как это устроено», где им и место.
    if reason == "cluster":
        return (f"Стечения {thing} не берёт: второй согласный может быть "
                f"у ребёнка не поставлен, а проверить не по чему — слов здесь нет.")
    if reason == "intervocal_line":
        return "Звуковая дорожка делается только на прямом слоге."
    if reason == "reverse_line":
        return ("Звуковая дорожка делается только на прямом слоге: линия — это "
                "тянущийся звук, а гласная в конце. Обратный слог — на слоговой.")
    if reason == "devoiced":
        return (f"Звонкий в конце слова оглушается: {syl} прочтётся с другим "
                f"звуком. Такого слога у этого звука не бывает.")
    if reason == "no_clean_cluster":
        return ("Стечений, чистых для этого ребёнка, нет: во всех вторым "
                "согласным стоит звук, который вы отметили как непоставленный.")
    if reason == "no_words":
        where = f"на {syl}" if syl != "такой слог" else "с таким слогом"
        return (f"Чистых слов {where} в картотеке не набирается — собирать "
                f"{MATERIAL_VIN.get(material, 'материал')} не из чего.")
    return ""


POSITION_LABEL_HUMAN = {
    "initial": "в начале слова",
    "medial": "в середине слова",
    "final": "в конце слова",
}


def why_position(reason: str, position: str = "") -> str:
    """Почему лабиринт не собирается на такой позиции звука."""
    where = POSITION_LABEL_HUMAN.get(position, "в этой позиции")
    if reason == "devoiced":
        return ("Звонкий согласный в конце слова оглушается — слов, которые "
                "кончаются на этот звук, в языке нет.")
    if reason == "no_words":
        return (f"Слов, где звук стоит {where}, в картотеке не набирается на "
                f"девять картинок.")
    return ""


# ── ПОЧЕМУ ИГРА НЕ СОБИРАЕТСЯ НА ЭТОМ ЛИСТЕ ────────────────────────────
# Факты (сколько примеров нашлось) считает движок, фразу лепим здесь.

def why_game(found: int, need: int = 4, reason: str = "") -> str:
    """Причина, по которой игра не собирается. Пусто = собирается."""
    # Со строчной буквы и без точки в конце: фраза договаривает предложение
    # «„Назови ласково“ на этом листе не собирается: …».
    if reason == "numerals":
        return ("числительные (один · два · пять) попали под запрет профиля, "
                "и строка счёта звучала бы с трудным для ребёнка звуком")
    if found <= 0:
        return (f"на словах этого листа не набирается ни одного примера, "
                f"нужно {need}")
    return (f"на словах этого листа набирается {found} "
            f"{'пример' if found == 1 else 'примера'} из {need} нужных")


GAME_DROPPED = ("Игра на страницу не поместилась и снята — на бумаге её нет. "
                "Возьмите другой тип слога или уберите материал на входе.")


def translate(warnings: List[str], kind: str = BLOCK) -> List[str]:
    """Машинные строки → человеческие. Дубли схлопываются, порядок сохраняется."""
    out: List[str] = []
    for w in warnings or []:
        text = None
        for rx, k, fn in RULES:
            m = rx.search(w)
            if m:
                text = fn(m, w)
                break
        if not text:
            # Либо строка незнакомая (жаргон, показывать нельзя), либо правило
            # решило, что логопеду тут говорить не о чем. След остаётся в raw.
            continue
        if text not in out:
            out.append(text)
    return out


def split(blocking: List[str], notes: List[str]) -> Dict[str, Any]:
    """Готовый блок warnings для браузера + сырьё для разработчика."""
    human_block = translate(blocking, BLOCK)
    human_notes = [t for t in translate(notes, NOTE) if t not in human_block]
    return {
        "blocking": human_block,
        "notes": human_notes,
        "raw": {"blocking": list(blocking or []), "notes": list(notes or [])},
    }


# ── ОТКАЗЫ ДВИЖКА ──────────────────────────────────────────────────────

_ENGINE_JARGON = re.compile(
    r"position_mode=\S+|allow_ambiguous=True|words_path=\S+|markova_max=\S+|"
    r"\(отсеяно \d+\)|отсеяно \d+|блок \[\d\]|канон [\d\[]|purity_scope|"
    r"каркасу «[^»]+»|скелет требует[^.;]*")


def error_message(text: str, thing: str = "лист") -> str:
    """Текст отказа движка → человеческий. Советы сохраняем, жаргон убираем."""
    t = str(text)

    if "чистых слов нет вообще" in t or "нашлось 0" in t:
        return (f"Для такого набора звуков {thing} не собирается: чистых слов "
                f"не осталось совсем.")
    if "нет стечений" in t:
        return (f"Среди подходящих слов нет ни одного со стечением согласных — "
                f"такой {thing} не из чего построить.")
    if "слоговой блок пуст" in t:
        return (f"Слоговые ряды построить не удалось: ни к одному слогу не "
                f"нашлось слова.")
    if "не собрать" in t and "лабиринт" in t:
        return ("Дорожку из девяти картинок не собрать: подходящих слов мало. "
                "Смените позицию звука кнопками сверху или снимите один звук справа.")
    if "словаря нет" in t:
        return "Такого звука в генераторе пока нет — собраны словари Р, С и Ш."

    cleaned = _ENGINE_JARGON.sub("", t)
    cleaned = re.sub(r"\s{2,}", " ", cleaned).strip(" ·;,—-")
    return cleaned or f"Такой {thing} не собирается."
