# -*- coding: utf-8 -*-
"""
human.py — ПЕРЕВОД С НАШЕГО ЯЗЫКА НА ЧЕЛОВЕЧЕСКИЙ.

Зачем. Движок говорит честно, но по-своему: «канон правило 11: слоговой материал
28 мм > ¼ словесного (107 мм) — сократите слоги». Всё это правда, но логопед
миллиметрами ничего не меряет, номеров блоков не знает и слова purity_scope
никогда не видел. Такой текст на экране — не честность, а неуважение.

Закон (автор, 2026-08-04): на экране не должно быть ни одного слова, которое
существует только у нас в коде и в переписке.

Что делает модуль: сворачивает 88 разных машинных строк в короткий список
человеческих сообщений. Каждое отвечает на два вопроса — ЧТО случилось и ЧТО
делать. Внутренние тексты не пропадают: они уходят в поле `raw` ответа, чтобы
разработчик мог посмотреть, но на экран не попадают.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Tuple

# Человеческие имена звуков для подстановки в текст
PH_LABEL = {
    "л": "Л", "л'": "Ль", "р": "Р", "р'": "Рь", "с": "С", "с'": "Сь",
    "з": "З", "з'": "Зь", "ц": "Ц", "ш": "Ш", "ж": "Ж", "щ": "Щ", "ч": "Ч",
    "й": "Й", "к": "К", "к'": "Кь", "г": "Г", "г'": "Гь", "х": "Х", "х'": "Хь",
}

BLOCK = "блок"    # печатать нельзя
NOTE = "заметка"  # к сведению


def _phonemes(text: str) -> List[str]:
    """Вытащить звуки из машинной строки вида «(л) · «Маляр» (л')»."""
    out: List[str] = []
    for m in re.finditer(r"\(([^)]{1,24})\)", text):
        for part in m.group(1).split(","):
            p = part.strip()
            if p in PH_LABEL and PH_LABEL[p] not in out:
                out.append(PH_LABEL[p])
    return out


# ── ПРАВИЛА ПЕРЕВОДА ───────────────────────────────────────────────────
# Порядок важен: первое совпавшее правило выигрывает.
# Каждое правило: (регулярка, вид, функция-текст).

MIN_WORDS = 12       # канон блока [4]


def _num(m: re.Match) -> int:
    """Первая непустая группа-число. Регулярки с альтернативами дают None."""
    for g in m.groups():
        if g and str(g).isdigit():
            return int(g)
    return -1


def _few_words(m: re.Match, text: str) -> str:
    n = _num(m)
    if n >= MIN_WORDS:
        # 12–24 — это норма. «Нашлось 15 из 16» не проблема, а деталь сборки:
        # логопеду показывать нечего.
        return ""
    return (f"Слов для этого листа нашлось мало — {n}. Обычно берут от 12: "
            f"меньше — ребёнку не на чем закрепить звук. "
            f"Снимите один звук справа или возьмите другой слог.")


def _syllables_outweigh(m: re.Match, text: str) -> str:
    return ("Слогов на листе получилось больше, чем слов. Для занятия это "
            "перекос: слоги — разминка, а закрепляется звук на словах.")


def _few_syllables(m: re.Match, text: str) -> str:
    return ("Слоговых рядов вышло меньше обычного — слов не хватило, чтобы "
            "каждый ряд закончился словом.")


def _did_not_fit(m: re.Match, text: str) -> str:
    if "блок [6]" in text or "предложения" in text:
        return ("Предложения на страницу не поместились и сняты. Попробуйте "
                "другой тип слога — материал будет короче.")
    return ("Не всё поместилось на страницу — часть слов пришлось снять. "
            "На бумаге ровно то, что вы видите.")


def _no_column(m: re.Match, text: str) -> str:
    syl = m.group(1).strip().rstrip(":")
    return (f"Для слога «{syl}» подходящих слов не нашлось — "
            f"эта колонка на листе пустая.")


def _no_game(m: re.Match, text: str) -> str:
    return ("Игру собрать не из чего: на этом наборе слов не набирается "
            "четырёх примеров. Блок с игрой на листе пропущен.")


def _no_chant(m: re.Match, text: str) -> str:
    return ("Чистоговорку составить не удалось: среди слов нет такого, на "
            "которое рифмуется слог. Блок пропущен.")


def _no_sentence(m: re.Match, text: str) -> str:
    return ("Часть предложений собрать не удалось — подходящих слов мало.")


def _few_sentences(m: re.Match, text: str) -> str:
    n = _num(m)
    return (f"Предложений получилось {n} — меньше обычных шести."
            if n > 0 else "Предложений получилось меньше обычного.")


def _dirty_names(m: re.Match, text: str) -> str:
    ph = _phonemes(text)
    kak = ", ".join(ph) if ph else "трудные для ребёнка"
    where = "названиях упражнений" if "упражнений" in text else "подсказке к звуку"
    return (f"В {where} есть звуки, которые ребёнку пока трудны ({kak}). "
            f"Эти слова читает взрослый — ребёнок их не повторяет. "
            f"Если хотите, замените их своими.")


def _fused(m: re.Match, text: str) -> str:
    pair = m.group(1) if m.lastindex else ""
    p = f" «{pair}»" if pair else ""
    return (f"Часть слоговых рядов убрана: сочетание{p} при чтении вслух "
            f"сливается в другой звук. Слова с ним на листе остались — в "
            f"словах оно звучит правильно.")


def _nothing_at_all(m: re.Match, text: str) -> str:
    return ("Для такого набора звуков чистых слов не осталось совсем. "
            "Снимите один звук справа или возьмите другой тип слога — "
            "подмешивать слова с трудными звуками генератор не станет.")


RULES: List[Tuple[re.Pattern, str, Any]] = [
    (re.compile(r"чистых слов нет вообще|нашлось 0 слов"), BLOCK, _nothing_at_all),
    (re.compile(r"канон \[4\]: слов (\d+)|слов (\d+) — меньше канонического"), BLOCK, _few_words),
    (re.compile(r"нашлось (\d+) слов из"), NOTE, _few_words),
    (re.compile(r"правило 11|слоговой блок \d+ рядов при"), BLOCK, _syllables_outweigh),
    (re.compile(r"канон \[3\]|слогов \d+ — меньше канонических"), NOTE, _few_syllables),
    (re.compile(r"НЕ ВЛЕЗАЛО|не влезало"), NOTE, _did_not_fit),
    (re.compile(r"колонки «([^»]+)» нет"), NOTE, _no_column),
    (re.compile(r"блок \[5\] пуст"), NOTE, _no_game),
    (re.compile(r"чистоговорка не построена"), NOTE, _no_chant),
    (re.compile(r"предложение из \d+ слов не собрано"), NOTE, _no_sentence),
    (re.compile(r"канон \[6\]: предложений (\d+)|предложений (\d+) — меньше"), NOTE, _few_sentences),
    (re.compile(r"содержат звуки из запрета|содержит звуки из запрета"), NOTE, _dirty_names),
    (re.compile(r"слоговые ряды сняты.*«([^»]+)»"), NOTE, _fused),
]


def translate(warnings: List[str], kind: str = BLOCK) -> List[str]:
    """Машинные строки → человеческие. Дубли схлопываются, порядок сохраняется."""
    out: List[str] = []
    for w in warnings or []:
        text = None
        for rx, k, fn in RULES:
            m = rx.search(w)
            if m:
                text = fn(m, w)
                break
        if not text:
            # Либо строка незнакомая (жаргон, показывать нельзя), либо правило
            # решило, что логопеду тут говорить не о чем. След остаётся в raw.
            continue
        if text not in out:
            out.append(text)
    return out


def split(blocking: List[str], notes: List[str]) -> Dict[str, Any]:
    """Готовый блок warnings для браузера + сырьё для разработчика."""
    human_block = translate(blocking, BLOCK)
    human_notes = [t for t in translate(notes, NOTE) if t not in human_block]
    return {
        "blocking": human_block,
        "notes": human_notes,
        "raw": {"blocking": list(blocking or []), "notes": list(notes or [])},
    }


# ── ОТКАЗЫ ДВИЖКА ──────────────────────────────────────────────────────

_ENGINE_JARGON = re.compile(
    r"position_mode=\S+|allow_ambiguous=True|words_path=\S+|markova_max=\S+|"
    r"\(отсеяно \d+\)|отсеяно \d+|блок \[\d\]|канон [\d\[]|purity_scope|"
    r"каркасу «[^»]+»|скелет требует[^.;]*")


def error_message(text: str, thing: str = "лист") -> str:
    """Текст отказа движка → человеческий. Советы сохраняем, жаргон убираем."""
    t = str(text)

    if "чистых слов нет вообще" in t or "нашлось 0" in t:
        return (f"Для такого набора звуков {thing} не собирается: чистых слов "
                f"не осталось совсем.")
    if "нет стечений" in t:
        return (f"Среди подходящих слов нет ни одного со стечением согласных — "
                f"такой {thing} не из чего построить.")
    if "слоговой блок пуст" in t:
        return (f"Слоговые ряды построить не удалось: ни к одному слогу не "
                f"нашлось слова.")
    if "не собрать" in t and "лабиринт" in t:
        return ("Дорожку из девяти картинок не собрать: подходящих слов мало. "
                "Смените позицию звука кнопками сверху или снимите один звук справа.")
    if "словаря нет" in t:
        return "Такого звука в генераторе пока нет — собраны словари Р, С и Ш."

    cleaned = _ENGINE_JARGON.sub("", t)
    cleaned = re.sub(r"\s{2,}", " ", cleaned).strip(" ·;,—-")
    return cleaned or f"Такой {thing} не собирается."
