VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")


def positions(tr):
    """Позиции мягкого [с'] в транскрипции (с апострофом сразу после)."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "с":
            continue
        if not (i + 1 < n and tr[i + 1] == SOFT):
            continue                       # твёрдый [с] — не цель
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 2] if i + 2 < n else None      # +2: перескочить апостроф
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            if prev in CONS:
                res.append("стечение в конце (С' вторым)")
            else:
                res.append("конец слова")
        elif prev in CONS:
            res.append("стечение (С' вторым)")
        elif nxt in CONS:
            res.append("стечение (С' первым)")
        else:
            res.append("середина между гласными")
    return res


def vowel_after(tr):
    """Гласная сразу после первого [с'] — важна для мягкости."""
    for i, ch in enumerate(tr):
        if ch == "с" and i + 1 < len(tr) and tr[i + 1] == SOFT:
            j = i + 2
            if j < len(tr) and tr[j] in VOWELS:
                return "СЬ+" + tr[j].upper()
            return "СЬ+согласный/конец"
    return "?"


