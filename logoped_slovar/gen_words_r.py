VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")

def positions(tr):
    """Позиции твёрдого р в транскрипции (без апострофа после)."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "р":
            continue
        if i + 1 < n and tr[i + 1] == SOFT:
            continue  # мягкий р' — сюда не должно попадать
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 1] if i + 1 < n else None
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            if prev in CONS:
                res.append("стечение в конце (Р вторым)")
            else:
                res.append("конец слова")
        elif prev in CONS:
            res.append("стечение (Р вторым)")
        elif nxt in CONS:
            res.append("стечение (Р первым)")
        else:
            res.append("середина между гласными")
    return res

def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "р" and not (i + 1 < len(tr) and tr[i + 1] == SOFT):
            j = i + 1
            if j < len(tr) and tr[j] in VOWELS:
                return "Р" + tr[j].upper()
    return "Р+согласный/конец"

