VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")


def positions(tr):
    """Позиции МЯГКОГО л' в транскрипции (л, за которым идёт апостроф)."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "л":
            continue
        if not (i + 1 < n and tr[i + 1] == SOFT):
            continue  # твёрдый л — сюда не должно попадать вовсе
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 2] if i + 2 < n else None
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            if prev in CONS:
                res.append("стечение в конце (Ль вторым)")
            else:
                res.append("конец слова")
        elif prev in CONS:
            res.append("стечение (Ль вторым)")
        elif nxt in CONS:
            res.append("стечение (Ль первым)")
        else:
            res.append("середина между гласными")
    return res


def has_hard_l(tr):
    """Есть ли в транскрипции ТВЁРДЫЙ л (без апострофа после)."""
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch == "л" and not (i + 1 < n and tr[i + 1] == SOFT):
            return True
    return False


def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "л" and i + 1 < len(tr) and tr[i + 1] == SOFT:
            j = i + 2
            if j < len(tr) and tr[j] in VOWELS:
                return "ЛЬ+" + tr[j].upper()
    return "ЛЬ+согласный/конец"


def yo_syllable(word):
    """Номер слога с буквой Ё (Ё в русском ВСЕГДА ударная). None, если Ё нет."""
    idx = 0
    for ch in word:
        if ch in VOWELS:
            idx += 1
            if ch == "ё":
                return idx
    return None


