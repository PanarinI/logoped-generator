# Смысл контракта не в координате, а в том, чтобы точка стояла ТАМ, ГДЕ ЛИНИЯ
# НАЧИНАЕТСЯ. Теперь она читается из самого пути (первая команда M), и форма
# вольна стартовать где хочет — контракт держится по существу, а не по букве.
#     path кончается в (w, yc); точка старта = первая точка path.
def _yc(h: float) -> float:
    return h / 2


def _path_straight(w: float, h: float) -> str:
    y = _yc(h)
    return f"M 0 {y:.1f} L {w:.1f} {y:.1f}"


def _path_wave(w: float, h: float, n: int = 3) -> str:
    """Синусоида: ровное непрерывное ведение."""
    y0, amp, pts = _yc(h), h * 0.30, []
    steps = 72
    for i in range(steps + 1):
        x = w * i / steps
        pts.append(f"{x:.1f} {y0 - amp * math.sin(2 * math.pi * n * i / steps):.1f}")
    return "M " + " L ".join(pts)


def _path_drift(w: float, h: float, rise: float) -> str:
    """Та же волна, но её ось ПЛАВНО идёт вверх (rise>0) или вниз (rise<0).

    Заменяет зигзаг, решение автора 08-25. Источник на стороне автора: Попова
    говорит «линия идёт вверх, и ребёнок старается произнести звук более звонко…
    линия вниз — голос ниже», и про острые углы не говорит ничего. Углы были
    нашей вольностью, выданной за приём. Плавная ось делает то же самое и не
    спорит с ведением пальца: рука не спотыкается на изломах.
    """
    # ⚠ 08-26, поймано глазами: при span = 0.30·h подъём на 250-миллиметровой
    # линии выходил около восьми миллиметров, и вторая дорожка не отличалась
    # от первой. А если разница не видна — задания на листе не три, а два.
    # Амплитуда волны заодно ужата: иначе подъём тонет в её собственных горбах.
    # ⚠ 08-26, поймано автором на листе [Щ]: линия «голос выше» РВАЛАСЬ посередине.
    # Считалось от центра: y = h/2 - 0.62·h·t. При t→1 это -0.12·h, то есть
    # ЗА ВЕРХНИМ КРАЕМ рамки, и SVG обрезал кусок. Разрыв читался как пунктир —
    # то есть лист показывал не то задание, которое подписано.
    # Теперь линия начинается НИЖЕ центра и приходит ВЫШЕ него, оставаясь внутри:
    # весь ход укладывается в рамку с запасом на амплитуду волны.
    amp = h * 0.15
    span = h * 0.44 * rise
    y0 = _yc(h) + span / 2          # старт ниже центра, финиш выше (или наоборот)
    pts = []
    steps = 72
    for i in range(steps + 1):
        t = i / steps
        x = w * t
        y = y0 - span * t - amp * math.sin(2 * math.pi * 3 * t)
        pts.append(f"{x:.1f} {y:.1f}")
    return "M " + " L ".join(pts)


def _path_arcs(w: float, h: float, n: int = 4) -> str:
    """Горки: голос идёт вверх-вниз (✅ Попова). Начало и конец — на линии."""
    y, seg = _yc(h), w / n
    top = h * 0.12
    d = [f"M 0 {y:.1f}"]
    for i in range(n):
        x0 = seg * i
        d.append(f"Q {x0 + seg / 2:.1f} {top:.1f} {x0 + seg:.1f} {y:.1f}")
    return " ".join(d)


def _path_loops(w: float, h: float, n: int = 5) -> str:
    """Петли: непрерывное ведение. ❓ Источник про них не говорит ничего —
    ни «просто», ни «сложно»; стоят среди непрерывных."""
    y, seg = _yc(h), w / n
    r = min(seg * 0.40, (y - 1.5) / 2.0)
    d = [f"M 0 {y:.1f}"]
    for i in range(n):
        x0 = seg * i
        d.append(f"C {x0 + seg * 0.12:.1f} {y - r * 2:.1f} "
                 f"{x0 + seg * 0.88:.1f} {y - r * 2:.1f} {x0 + seg:.1f} {y:.1f}")
    return " ".join(d)


def _path_spiral(w: float, h: float, turns: float = 2.6) -> str:
    """«Улитка» — простейший вариант (✅ Попова: «Вариант 1. Самый простой»).

    Форма переписана 2026-08-23 по слову автора: «это по-твоему улитка? по-моему
    херь какая-то». И он прав — здесь была ПРЯМАЯ с маленьким завитком
    посередине. Ребёнок вёл палец по прямой, а завиток оказывался препятствием
    на пути, а не самим путём; задачу «тяни не прерываясь» прямая решает и без
    него. (До этого была спираль во всю строку, читавшаяся как каракуля, —
    значит обе прошлые попытки промахнулись в разные стороны.)

    Что рисуем теперь — раковина, которая РАСКРУЧИВАЕТСЯ:
      · палец стартует в ЦЕНТРЕ завитка сразу за героем;
      · идёт наружу, витки становятся шире — это и есть улитка;
      · последний виток распрямляется в ровный ход вправо, к букве.

    Почему из центра наружу, а не снаружи внутрь: классическая улитка кончается
    в середине, а у нас финиш обязан стоять справа у буквы — там слог. Развернув
    ход, получаем и настоящую спираль, и порядок слева направо (локальный закон
    8: порядок движения пальца = порядок звучания).
    """
    y = _yc(h)
    # Центр раковины — в левой четверти, чтобы на разгон вправо осталось место.
    cx = w * 0.19
    rmax = min(h * 0.44, w * 0.14)
    steps = 240
    pts: List[str] = []
    # Спираль Архимеда: радиус растёт линейно, угол — равномерно. Стартовый
    # угол подобран так, чтобы ПОСЛЕДНЯЯ точка витка шла вправо: тогда выход
    # в прямую получается без излома.
    start_ang = math.pi / 2
    total = 2.0 * math.pi * turns
    ex = ey = 0.0
    for i in range(steps + 1):
        t = i / steps
        ang = start_ang + total * t
        rr = rmax * t
        x = cx + rr * math.cos(ang)
        yy = y + rr * math.sin(ang)
        pts.append(f"{'M' if i == 0 else 'L'} {x:.1f} {yy:.1f}")
        ex, ey = x, yy
    # Выход к букве: плавная дуга от конца витка на среднюю высоту, дальше ровно.
    run = cx + rmax * 1.15
    pts.append(f"Q {ex + (run - ex) * 0.55:.1f} {ey:.1f} {run:.1f} {y:.1f}")
    pts.append(f"L {w:.1f} {y:.1f}")
    return " ".join(pts)


def _path_zigzag(w: float, h: float, n: int = 6) -> str:
    """Зигзаг: резкая смена высоты голоса. Концы — на линии."""
    y, seg = _yc(h), w / n
    hi, lo = h * 0.16, h * 0.84
    d = [f"M 0 {y:.1f}"]
    for i in range(n):
        d.append(f"L {seg * (i + 0.5):.1f} {hi if i % 2 == 0 else lo:.1f}")
        d.append(f"L {seg * (i + 1):.1f} {y:.1f}")
    return " ".join(d)


