    _strips = m.get("family") == "strips"
    _n = int(m.get("rows") or 3)
    _pg = "A4 landscape" if _strips else "A4"
    _pw, _ph = (PAGE_H, PAGE_W) if _strips else (PAGE_W, PAGE_H)
    _lw = _pw - MARGIN_L - MARGIN_R
