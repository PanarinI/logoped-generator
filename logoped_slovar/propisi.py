    # ⚠ 08-26. Считалось «поля 20 · шапка 26 · подвал 16», и лист уезжал на
    # ВТОРУЮ страницу — все шесть пробных PDF вышли двухстраничными. Замер по
    # вёрстке: шапка с заголовком и заданием берёт ~34 мм (10.5pt строка +
    # h1 14pt с отступом 5 + задание 12pt с отступом 6), подвал ~22 мм
    # (отступ 6 + три строки 9.5pt). На экране этого не видно: там страница
    # тянется, а бумага — нет.
    # Подвал не постоянной высоты: он перечисляет РЕАЛЬНЫЕ ступени листа, и на
    # четырёх дорожках фраза длиннее, чем на двух. Поэтому вычитается не число,
    # а число ПЛЮС строка на каждую ступень сверх двух — иначе лист из четырёх
    # уезжал на вторую страницу, а из двух зря пустовал.
    _free = _ph - 20.0 - 34.0 - (22.0 + 4.0 * max(0, _n - 2))
    _rh = max(26.0, _free / max(1, _n))
    # ⚠ 08-26. Тут стояло `_rh - 8`, и строки НАЕЗЖАЛИ друг на друга: в полосе
