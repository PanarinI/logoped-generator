    # лестница снята, все дорожки на листе одной формы (08-26).
    _LW = {"тяни слитно": "плавная — тянуть слитно",
           "голос выше": "идущая вверх — вести голос выше",
           "голос ниже": "идущая вниз — вести голос ниже"}
    _ladder_words = _LW.get(m.get("line_label", ""), m.get("line_label", ""))

