#     гласную = слог → назвали картинки = слова (deti-i-mama.ru);
#   • попутно работает «содружество глаз — рука», нужное потом для чтения.
#
# ЧТО МЕНЯЕТСЯ ОТ ВАРИАНТА К ВАРИАНТУ — ✅ Попова Н.О., nsportal 19.05.2022,
# «Звуковые дорожки для автоматизации звука Р», дословно:
#   В1 «Ребенок произносит звук Р и проводит пальчиком по линии стараясь дойти
#       до финиша. Главная задача произносить звук не прерываясь»
#   В2 «Ребенок произносит звук, двигаясь по ПРЯМЫМ линиям. Линия идет вверх, и
#       ребенок старается произнести звук более звонко или мягко, линия-вниз
#       голос необходимо сделать ниже»
#   В3 «Используются звуковые дорожки с ПРЕРЫВИСТЫМИ линиями. Ребёнку
#       необходимо коротко или длинно произносить звук»
#
# ⚡ Отсюда закон этого материала: **форма линии — это инструкция голосу**, и
# нарастает она по трудности речевой, а не моторной. Каждая строка ниже несёт
# ту задачу, которую источник ей и приписывает.
#
# ⛔ ЧТО СНЯТО: лестница «нарастает ДЛИНА при одной форме» (наше решение утром
# 08-06). Ни один источник длины не упоминает вообще, а форму — все. Держать
# 🔶-гипотезу там, где есть ✅-источник, — брак по закону проекта №1.
# ⛔ ПУНКТИР ПЕРЕСТАЛ БЫТЬ ОФОРМЛЕНИЕМ. Раньше пунктирными печатались ВСЕ три
# строки, и рядом стояло «не отрывая пальца» — то есть самый трудный вариант
# по Поповой выдавался за самый лёгкий. Теперь прерывистая линия ровно одна —
# третья, и подпись под ней говорит то же, что источник.
#
# 🔶 Что здесь остаётся нашим: конкретный рисунок первой строки (пологая волна).
# Источник требует от неё только НЕПРЕРЫВНОСТИ, форму не называет.
# 🔶 И перенос лестницы на слоговую ступень: Попова описывает изолированный
# звук. Подпирается образцами практиков у Ольги (7 из 10 — три строки одного
