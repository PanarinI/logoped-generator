MODES = ("isolated", "syllable")


def build_propisi(sound: str = "р",
                  syl_type: str = "direct",
                  vowel: Optional[str] = None,
                  seed: int = 0,
                  mode: str = "syllable",
                  profile: Any = (),
                  rows: int = 3,
                  line: str = "wave",
                  frame_pick: str = "",
                  colour: bool = False) -> Dict[str, Any]:
    """Звуковая дорожка.

    mode="isolated" — только звук, гласной в конце нет (ступень ДО слога);
    mode="syllable" — линия + гласная, собирается слог.

    rows — сколько дорожек на листе, 1..4. Это КОНСТРУКТОР, решение автора 08-25:
    выбирает логопед под ребёнка, а не мы за него. Малышу — одна большая, ребёнку
    постарше — четыре разных.
    ⚡ `rows == 1` переключает СЕМЬЮ ЛИСТА, а не просто количество: одна дорожка
    печатается СПИРАЛЬЮ на книжном листе (картинка из банка целиком), 2-4 —
    полосами на альбомном. Так устроен жанр, см. `SPIRAL_BY_HERO`.
    line — форма линии, одна на весь лист. Ручки на экране у неё нет (08-26):
    прерывистая снята целиком, а подъём и спуск движок умеет, но не показывает.
    Зигзаг снят решением автора 08-25: высота голоса делается плавным подъёмом
    обычной линии, острые углы не нужны, и у Поповой их нет — она говорит
    «линия идёт вверх… линия вниз».
    """
    # ⛔ ЧЕТВЁРТАЯ ДОРОЖКА СНЯТА 08-26, слово автора: «4 дорожки на лист при
    # условии, что одна повторяется — это полный бред… я имел в виду другое:
    # логопед хочет сэкономить бумагу и берёт 4 на лист — но это имеет смысл,
    # только если он может настроить КАЖДУЮ». Пока все дорожки листа несут одно
    # и то же задание, четыре копии — не экономия, а четыре одинаковых листа
    # на одной странице. Остаются 1 · 2 · 3.
    rows = max(1, min(3, int(rows or 3)))
    if mode not in MODES:
        raise PropisiError(
            "у звуковой дорожки две ступени: «только звук» и «звук + слог»")
    if sound not in C.WORDS_BY_SOUND:
        raise PropisiError(
            f"звука [{_P.sound_label(sound)}] в генераторе нет; собраны: "
            + ", ".join(_P.sound_label(s) for s in sorted(C.WORDS_BY_SOUND)))
    if syl_type not in PROPISI_TYPES:
        raise PropisiError(
            "на звуковой дорожке линия — это сам тянущийся звук, значит "
            "согласный стоит в начале пути, а гласная в конце. Возьмите "
            "прямой слог или стечение в начале.")

    # Рамку стечения («др», «тр») даёт словарь, отфильтрованный ПРОФИЛЕМ
    # ребёнка: второй согласный приходит не из головы, а из живого слова,
    # прошедшего тот же отбор, что и лист. Пусто — законных стечений у этого
    # ребёнка нет, и молчать нельзя (закон 12).
    frame, frames_all = "", []
    if syl_type == "cluster_onset":
        _frames = C.cluster_frames_for(sound, syl_type, profile, n_rows=4,
                                       seed=seed)
        if not _frames:
            raise PropisiError(
                "стечений, чистых для этого ребёнка, в картотеке не "
                "набирается: во всех найденных вторым согласным стоит звук, "
                "который вы отметили как непоставленный. Снимите один звук "
                "справа или возьмите прямой слог.")
        # Гибкость при точности: движок уже посчитал, какие рамки ЗАКОННЫ для
        # этого ребёнка, — значит их надо не прятать за кубиком, а показать и
        # дать выбрать. Волюнтаризмом выглядело именно то, что рамка была одна
        # и бралась молча (слово автора 08-26: «почему на Щ это НЩ? бред»).
        frames_all = [C.ortho(f) for f in _frames]
        frame = frame_pick if frame_pick in _frames else _frames[seed % len(_frames)]

    # Ряд гласных берём НЕ у листа: там четвёрка потому, что действует правило 11
    # («слоговой блок ≤ ¼ словесного»), а здесь словесного блока нет вовсе.
    vowels = list(C.SYL_VOWELS_TRACK if not C.is_soft_target(sound)
                  else C.SYL_VOWELS_SOFT + ("э",))
    if vowel not in vowels:
        vowel = vowels[seed % len(vowels)]

    if mode == "isolated":
        # На этой ступени гласной нет вовсе: ребёнок тянет один звук.
        # Тип слога тоже ни на что не влияет — тянуть можно только сам звук.
        vowel, phon, syllable = "", "", ""
    else:
        phon = C._syllable_text(sound, vowel, syl_type, frame)
        syllable = C.ortho(phon)
        # Целевой звук обязан уцелеть в том, что попадёт на бумагу. У звонких
        # в конце слова оглушение обязательно: «аж» читается [аш].
        if not C.syllable_keeps_sound(sound, syllable):
            raise PropisiError(
                f"обратного слога у звука [{_P.sound_label(sound)}] не бывает: "
                f"звонкий согласный в конце слова оглушается, «{syllable}» "
                f"звучит как [{_P.sound_label(C.ph.analyze(syllable).transcription[-1])}]. "
                f"Такой лист учил бы ребёнка не тому звуку. Возьмите прямой слог.")
    image = _image_for(sound)
    # Подпись над линией показывает, ЧТО тянуть, пока едешь (так на образцах
    # Ольги). На стечении тянется не голый звук: ребёнок начинает с «др» и
    # продолжает [р]. Печатаем «др-р-р», иначе подпись зовёт не то, что в
    # заголовке, — и это была бы наша же болезнь «слог СЁ, а у финиша О».
    if frame:
        _u = str(image.get("utterance") or "")
        _tail = _u.split("-", 1)[1] if "-" in _u else _u
        image = dict(image, utterance=C.ortho(frame) + "-" + _tail)

    # Виды героя и цели крутятся ОТ SEED, а не выбираются ручкой: выбор между
    # «легковая едет в гараж» и «на мост» логопеду безразличен, а вариативность
    # нужна. Её даёт кубик «собрать другой набор», который на экране уже есть
    # (закон 13: где выбор безразличен — ручки нет, есть кубик).
    _vidy = hero_vidy(image["name"]) or [""]
    _tseli = hero_tseli(image["name"]) or [""]

    line = line if line in LINE_FORMS else "wave"
    _fn = line_fn(line)
    lines: List[Dict[str, Any]] = []
    for _i in range(rows):
        hint = LINE_HINT[line]
        fn, task_label = _fn, LINE_LABEL[line]
        lines.append({
            "task_label": task_label,
            "hint": hint,
            "_fn": fn,
            # свой вид героя на каждой строке — в жанре герои разные, не один
            # повторённый (образец [Л] с тремя самолётами, 08-25)
            "vid": _vidy[(_i + seed) % len(_vidy)],
            "tsel": _tseli[(_i + seed) % len(_tseli)],
        })

    return {
        "lines": lines,
        "meta": {
            "mode": mode,
            "sound": sound,
            "sound_label": _P.sound_label(sound),
            "syl_type": syl_type,
            "type_label": C.SYL_TYPE_LABEL.get(syl_type, syl_type),
            "vowel": vowel,
            # Весь ряд гласных, из которого логопед выбирает. До 08-24 гласную
            # молча крутил кубик, и выбора у логопеда не было вовсе — он видел
            # «переключаются гласные» и не понимал, чем управляет.
            "vowels": vowels,
            "syllable": syllable,
            "syllable_phon": phon,
            "frame": C.ortho(frame) if frame else "",
            "frames": frames_all,          # какие рамки законны у этого ребёнка
            "line": line,
            "line_label": LINE_LABEL[line],
            "utterance": image["utterance"],
            "image_name": image["name"],
            "image_tier": image["tier"],
            "n_rows": len(lines),
            # Семья листа. Одна дорожка = спираль на книжном, 2-4 = полосы
            # на альбомном (ориентация подтверждена образцами жанра 08-25).
            "rows": rows,
            "family": "spiral" if rows == 1 else "strips",
            "hero": image["name"],
            "spiral": spiral_name(image["name"]) if rows == 1 else "",
            "spiral_url": (("/dorozhka/%s/%s.png"
                            % ("colour" if colour else "bw",
                               spiral_name(image["name"])))
                           if rows == 1 and spiral_name(image["name"]) else ""),
        },
    }


def _e(s: Any) -> str:
    return html.escape(str(s), quote=True)


def render_propisi(p: Dict[str, Any], colour: bool = False) -> str:
    """Структура -> печатный HTML одного листа А4 (ч/б).

    Устройство взято с образцов Ольги (ГОЛОСА.md, разбор 08-06): слева
    ПЕРСОНАЖ, издающий звук, — один и тот же во всех трёх строках; над линией
    подпись, что тянуть; справа — то, к чему приехали (у нас гласная).
    """
    m = p["meta"]
    label, syll, vowel = m["sound_label"], m["syllable"], m["vowel"]
    utter = m["utterance"] or f"{m['sound']}-{m['sound']}-{m['sound']}"
    isolated = m.get("mode") == "isolated"

    # Инструкция обязана описывать ТО, что напечатано. На обратном слоге
    # порядок зеркальный (гласная первой), значит и фраза другая: иначе лист
    # просит тянуть звук до гласной, которая уже сказана.
    # ⚠ 08-26: тут было вшито «Три дорожки — три разных задания», а дорожек
    # теперь 2-4. На листе из четырёх лист врал прямым текстом. Закон 2:
    # материал не имеет права утверждать больше, чем мы можем показать.
    _LINE_TASK = {
        "wave": "Тяни звук слитно, не прерываясь.",
        "up": "Линия идёт вверх — веди голос выше.",
        "down": "Линия идёт вниз — веди голос ниже.",
    }
    _NN = {1: "Одна дорожка.", 2: "Две одинаковые дорожки.",
           3: "Три одинаковые дорожки."}
    # Подсказка под каждой линией снята 08-26: пока была лестница, строки несли
    # РАЗНЫЕ задания и подпись была нужна; теперь они одинаковые, и три копии
    # одной фразы — это шум. Задачу говорит одна строка сверху.
    _tail = (_NN.get(int(p["meta"].get("rows") or 3), "Дорожки одинаковые.")
             + " " + _LINE_TASK.get(p["meta"].get("line", "wave"), "") + "</p>")
