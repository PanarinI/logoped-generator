    for i, ln in enumerate(p["lines"], 1):
        # Длина у всех строк одна: она больше ничего не кодирует, и форма линии
        # у всех дорожек листа тоже одна (лестница снята 08-26).
        w = (_lw - _vw - (_tw + 6.0 if isolated else 14.0)) if _strips \
            else (LINE_W - 46.0)
        _h = _th if _strips else TRACK_H
        d = ln["_fn"](w, _h)
        # Прерывистой линии в генераторе нет (08-26): обводка всегда сплошная.
        dash = ''
        # ПОРЯДОК СЛЕВА НАПРАВО = ПОРЯДОК ЗВУЧАНИЯ. Поймано автором 08-09:
        # на обратном слоге лист печатал персонажа слева и «А» справа, то есть
        # ребёнок вёл палец от [л] к [а] и читал «ЛА» вместо «АЛ» — материал
        # на обратный слог учил прямому. Прямой слог: тянем звук → приходим к
        # гласной. Обратный: сказали гласную → тянем звук до персонажа.
        # У изолированной ступени порядка нет: гласной там не существует.
        # Герой рисуется НЕ здесь: он один на все три дорожки и стоит колонкой
        # слева (см. ROW_H). Ребёнок встречает одно существо, а не три копии.
        # ⚠ У финиша печатается СЛОГ, а не фонемная гласная. До 08-23 здесь стоял
        # `vowel.upper()` — фонема, — и на 22 сочетаниях из 55 ребёнок видел у
        # финиша букву, которой в его слоге нет: заголовок «слог СЁ», а у финиша
        # «О»; «слог ШИ» — а у финиша «Ы». Поймано автором на глаз («сь-сь-сь-о —
        # непонятно») и воспроизведено прогоном 11 звуков × 5 гласных.
        #
        # Слог у финиша — не наша выдумка: ровно так просит произнести Борисова
        # 2008 («обвести трафарет и произнести: с-са»), и так же устроены образцы
