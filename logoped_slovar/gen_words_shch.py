OPPOSITION = {"с", "с'", "з", "з'", "ц", "ш", "ж", "ч"}
HISSING = {"ш", "ж", "ч"}                    # шипящие без цели
WHISTLING = {"с", "с'", "з", "з'", "ц"}      # свистящие
BACKLING = {"к", "к'", "г", "г'", "х", "х'"} # заднеязычные


def positions(tr):
    """Позиции [щ] в транскрипции. Щ всегда мягкий — апострофа не бывает."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "щ":
            continue
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 1] if i + 1 < n else None
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            res.append("стечение в конце (Щ вторым)" if prev in CONS else "конец слова")
        elif prev in CONS:
            res.append("стечение в середине (Щ вторым)")
        elif nxt in CONS:
            res.append("стечение в середине (Щ первым)")
        else:
            res.append("середина между гласными")
    return res


def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "щ":
            j = i + 1
            if j < len(tr) and tr[j] in VOWELS:
                return "Щ" + tr[j].upper()
    return "Щ+согласный/конец"


