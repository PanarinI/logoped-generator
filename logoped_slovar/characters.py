# Мягкая пара берёт рисунок твёрдой: «моторчик» — тот же мотор. Это канон
# (образ у пары один), а не экономия: у Фомичёвой и Спивак мягкий звук не
# получает своего существа, он получает тот же — только «маленький».
SOFT_TWIN: Dict[str, str] = {
    "моторчик": "мотор", "самолётик": "самолёт", "насосик": "насос",
}


# Винительный падеж имени героя — для задания «Проведи <кого> по тропе».
# Таблицей, а не правилом: у одушевлённых (комарик, жук) винительный совпадает
# с родительным, у неодушевлённых — с именительным, а «щётка» и «змея» дают
# ещё и смену окончания. Это тот же локальный закон 7 («правило врёт — таблица
# работает»), только на десяти словах. Поймано на бумаге 08-10: лист печатал
# «Проведи щётка по тропе».
ACCUSATIVE: Dict[str, str] = {
    "мотор": "мотор", "моторчик": "моторчик",
    "самолёт": "самолёт", "самолётик": "самолётик",
    "насос": "насос", "насосик": "насосик",
    "комарик": "комарика", "жук": "жука",
    "змея": "змею", "щётка": "щётку",
}


def accusative(name: str) -> str:
    """Имя героя в винительном падеже. Незнакомое имя возвращаем как есть."""
    return ACCUSATIVE.get(name or "", name or "")


def _resolve(name: str) -> str:
    return SOFT_TWIN.get(name or "", name or "")


def has_character(name: str) -> bool:
    return _resolve(name) in CHARACTERS


def character_svg(name: str, width_mm: float = 22.0,
                  stroke: float = 2.2) -> Optional[str]:
    """Готовый <svg> персонажа или None, если рисунка ещё нет.

    None — законный ответ: пока нарисован не весь реестр, лист обязан уметь
    обойтись без картинки и не притворяться, будто она есть."""
    body = CHARACTERS.get(_resolve(name))
    if not body:
        return None
    h = width_mm * 0.70
    return (f'<svg class="chr" viewBox="0 0 100 70" width="{width_mm:.1f}mm" '
            f'height="{h:.1f}mm" xmlns="http://www.w3.org/2000/svg" '
            f'fill="none" stroke="#000" stroke-width="{stroke}" '
            f'stroke-linecap="round" stroke-linejoin="round" '
            f'aria-hidden="true">{body}</svg>')
