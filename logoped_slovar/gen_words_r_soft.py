def skeleton(s):
    """Согласный скелет: только согласные буквы/звуки, без мягкости и гласных."""
    return [ch for ch in s if ch in CONS]


def ortho_skeleton(word):
    """Согласный скелет ПИСЬМА: йотация Е Ё Ю Я учтена, двойные согласные сжаты.

    Считается независимо от транскрипции — это вторая пара глаз к руке.
    """
    out = []
    prev = ""
    for ch in word:
        if ch in "еёюя" and (prev == "" or prev in "аеёиоуыэюя" or prev in "ьъ"):
            out.append("й")
        if ch in CONS and prev != ch:     # двойное СС в «принцесса» = один звук
            out.append(ch)
        prev = ch
    return out


