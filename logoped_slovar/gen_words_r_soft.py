VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")


def positions(tr):
    """Позиции МЯГКОГО р' в транскрипции (р с апострофом сразу после)."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "р":
            continue
        if not (i + 1 < n and tr[i + 1] == SOFT):
            continue  # твёрдый р — сюда не должно попадать вообще
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 2] if i + 2 < n else None      # символ ПОСЛЕ апострофа
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            if prev in CONS:
                res.append("стечение в конце (Р' вторым)")
            else:
                res.append("конец слова")
        elif prev in CONS:
            res.append("стечение (Р' вторым)")
        elif nxt in CONS:
            res.append("стечение (Р' первым)")
        else:
            res.append("середина между гласными")
    return res


def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "р" and i + 1 < len(tr) and tr[i + 1] == SOFT:
            j = i + 2
            if j < len(tr) and tr[j] in VOWELS:
                return "РЬ+" + tr[j].upper()
    return "РЬ+согласный/конец"


