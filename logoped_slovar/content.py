MATERIAL_BLOCKS: Tuple[str, ...] = ("syllables", "words", "game", "sentences",
                                    "chistogovorka")


def _material_texts(content: Dict[str, Any]) -> List[Tuple[str, str]]:
    """(блок, текст) по всему РЕЧЕВОМУ материалу листа."""
    out: List[Tuple[str, str]] = []
    for row in content["syllables"]["rows"]:
        for u in row["units"]:
            out.append(("syllables", u))
        out.append(("syllables", row["bond"]["word"]))
    for g in content["words"]["groups"]:
        for it in g["items"]:
            out.append(("words", it["word"]))
    game = content.get("game")
    if game:
        for it in game["items"]:
            out.append(("game", it["prompt"]))
            out.append(("game", it["answer"]))
        out.append(("game", game["sample"].replace("Образец:", " ")))
    for s in content["sentences"]["items"]:
        out.append(("sentences", s["text"]))
    if content.get("chistogovorka"):
        out.append(("chistogovorka", content["chistogovorka"]["text"]))
    return out


def verify_purity(content: Dict[str, Any]) -> None:
    """Правила 1-3. Падает, если в речевой материал попала запрещённая фонема."""
    banned = frozenset(content["meta"]["banned"])
    bad: List[str] = []
    for block, text in _material_texts(content):
        for tok in _tokens(text):
            dirty = corrigible_of(tok) & banned
            if dirty:
                bad.append(f"[{block}] {tok!r} содержит {sorted(dirty)}")
    if bad:
        raise PurityViolation(
            "нарушен фильтр чистоты (правила 1-3):\n  " + "\n  ".join(bad))


def verify_crosscut(content: Dict[str, Any]) -> None:
    """Правило 13. Падает, если игра/предложения/чистоговорка используют слово,
    которого нет ни в блоке [4], ни в объявленных производных, ни в служебных."""
    vocab = content["vocabulary"]
    # слоги блока [3] — не слова, но законная часть чистоговорки («ра-ра-ра — …»)
    # Глаголы предложений — четвёртый ЗАЯВЛЕННЫЙ источник (с 2026-08-08).
    # Правило 13 держит смысл «ничего с потолка»: каждое слово листа пришло из
    # места, которое можно назвать. Канон Фомичёвой про «базу отработанных
    # слов» относится к словарю ребёнка; глагол, несущий целевой звук, сам
    # является отрабатываемым материалом и проходит тот же фильтр чистоты.
    allowed: Set[str] = (set(vocab["block4"]) | set(vocab["derived"])
                         | set(vocab["service"]) | set(vocab["syllables"])
                         | set(vocab.get("verbs", ())))
    leaked: List[str] = []
    checked: List[Tuple[str, str]] = []
    if content.get("game"):
        checked.append(("game", content["game"]["sample"]))
        for it in content["game"]["items"]:
            checked.append(("game", it["prompt"]))
            checked.append(("game", it["answer"]))
    for s in content["sentences"]["items"]:
        checked.append(("sentences", s["text"]))
    if content.get("chistogovorka"):
        checked.append(("chistogovorka", content["chistogovorka"]["text"]))
    for block, text in checked:
        for tok in _tokens(text):
            if tok == "образец":
                continue
            if tok not in allowed:
                leaked.append(f"[{block}] {tok!r}")
    # производная форма обязана ссылаться на лемму из блока [4]
    for form, lemma in vocab["derived"].items():
        if lemma not in set(vocab["block4"]):
            leaked.append(f"[derived] {form!r} ссылается на {lemma!r} вне блока [4]")
    if leaked:
        raise CrosscutViolation(
            "нарушено правило сквозного словаря (13): " + ", ".join(sorted(set(leaked))))


