def cluster_frames_for(sound: str, syl_type: str,
                       profile: Iterable[str] = frozenset(),
                       n_rows: int = 4, seed: int = 0) -> List[str]:
    """Стечения, которые у ЭТОГО ребёнка законны, — для материалов БЕЗ слов.

    Зачем. Дорожки слов не печатают, и до 08-23 стечения им были запрещены
    наглухо: «в стечении есть второй согласный, а его чистоту без словаря не
    проверить». Это было верно ровно до тех пор, пока логопед не сказал, каких
    звуков у ребёнка нет, — а он говорит это на том же экране, профилем.
    Слово автора 08-23: «мы же это выбирали на листе автоматизации, значит
    здесь нужно это поле выбора».

    Проверять есть по чему: берём те же слова и тот же отбор, каким пользуется
    лист, и достаём из них те же рамки стечений. Второй согласный приходит не
    из головы, а из живого слова, прошедшего фильтр по профилю, — то есть
    ровно так же честно, как на листе.

    Пусто — законных стечений нет; звать материал не о чем.
    """
    if syl_type not in ("cluster_onset", "cluster_coda"):
        return []
    profile = frozenset(profile)
    banned = banned_phonemes(sound, profile)
    rnd = random.Random(f"frames|{sound}|{syl_type}|{sorted(profile)}|{seed}")
    rows = load_words(_words_path(sound, None))
    groups, _rejected, _left = _select_words(
        sound, syl_type, banned, rows, 16, 1, rnd, None, 1)
    if not groups:
        return []
    return _cluster_frames(groups, syl_type, n_rows, [])


def build_content(sound: str = "р",
                  syl_type: str = "direct",
                  profile: Iterable[str] = frozenset(),
                  sheet_no: int = 1,
                  seed: int = 0,
                  *,
                  n_words: int = 16,
                  n_sentences: int = 8,
                  n_game_items: int = 6,
                  game_kind: str = "",
                  markova_max: Optional[int] = None,
                  min_familiarity: int = 1,
                  words_path: Optional[str] = None,
                  allow_rule_diminutive: bool = False,
                  child_name: str = "") -> Dict[str, Any]:
    """Собрать наполнение листа автоматизации.

    sound      — целевой звук (ключ фонемы движка: 'р').
    syl_type   — один тип слога на лист: direct | reverse | intervocal |
                 cluster_onset | cluster_coda  (правило 8).
    profile    — множество НАРУШЕННЫХ у ребёнка фонем.
    sheet_no   — номер листа; сдвигает срез словаря (лист №2 ≠ листу №1).
    seed       — детерминированная вариативность (в т. ч. выбор игры).
    """
    if syl_type not in SYL_TYPES:
        raise ContentError(f"syl_type={syl_type!r}; допустимы: {', '.join(SYL_TYPES)}")
    if not (12 <= n_words <= 24):
        raise ContentError("n_words вне канона: 12-24 слова в блоке [4]")
    if not (6 <= n_sentences <= 10):
        raise ContentError("n_sentences вне канона: 6-10 предложений в блоке [6]")
    if sheet_no < 1:
        raise ContentError("sheet_no начинается с 1")

    profile = frozenset(profile)
    banned = banned_phonemes(sound, profile)
    rnd = random.Random(f"{sound}|{syl_type}|{sorted(profile)}|{sheet_no}|{seed}")
    warnings: List[str] = []

    rows = load_words(_words_path(sound, words_path))
    groups, rejected, leftovers = _select_words(
        sound, syl_type, banned, rows, n_words,
        sheet_no, rnd, markova_max, min_familiarity)
    found = sum(len(g["items"]) for g in groups)
    if found == 0:
        raise ContentError(
            "для этого профиля и типа слога чистых слов нет вообще. "
            + _shortfall_message(0, n_words, rejected, markova_max, min_familiarity))
    if found < n_words:
        warnings.append(_shortfall_message(found, n_words, rejected,
                                           markova_max, min_familiarity))
    _min_words = canon_min_words(syl_type)
    if found < _min_words:
        warnings.append(f"слов {found} — меньше канонического минимума "
                        f"{_min_words} (блок [4])")
    empty = [v for v in vowels_for(sound, syl_type)
             if v not in {g["vowel"] for g in groups}]
    for v in empty:
        warnings.append(
            f"колонки «{_group_header(sound, v, syl_type)}» нет: чистых слов с этим "
            f"сочетанием в словаре не нашлось (слог в блоке [3] остаётся, слова к нему нет)")

    derived: Dict[str, str] = {}
    service = _service_pool(sound, banned)

    syllables = _build_syllables(sound, syl_type, groups, found, rnd, warnings)

    # Слоговой ряд построен — теперь известно, на что рифмовать. Если ни одно
    # выбранное слово не годится, меняем одно (см. _ensure_rhyme).
    _row_syls = [u for r in syllables.get("rows", [])
                 for u in r.get("units_phon", r.get("units", []))]
    if _row_syls:
        _ensure_rhyme(groups, leftovers, _row_syls, banned, warnings)
    games_offer: Dict[str, Dict[str, Any]] = {}
    game = _build_game(groups, banned, seed, sheet_no, derived, warnings,
                       allow_rule_diminutive, service, n_game_items, game_kind,
                       offer=games_offer)
    sentences = _build_sentences(groups, sound, banned, service, rnd,
                                 n_sentences, warnings)
    # ⚠ Рифму НЕЛЬЗЯ искать по всему словарю: правило 13 «сквозной словарь»
    # требует, чтобы каждое слово блоков [5][6][7] пришло из блока [4].
    # Это КАНОН (Фомичёва: «автоматизация в предложениях проводится на базе
    # отработанных слов»), а не наш потолок — проверено 08-08: попытка отдать
    # сюда весь словарь уронила линтер на 'сестра'. Значит чистоговорку чинит
    # не расширение поиска, а СЛОВАРЬ (слова с ударным конечным слогом) плюс
    # предпочтение таких слов при отборе в блок [4].
    chisto = _build_chistogovorka(groups, sound, syllables, banned, service,
                                  rnd, derived, warnings)
    # «Вставь пропущенный слог» — ✅ Жихарева с. 36. Стоит рядом со словами:
    # он работает на них же, значит сквозной словарь не нарушается.
    fill = _build_fill_syllable(groups, syl_type, syllables)

    # [1] и [2] — из разобранного источника, а не из головы
    gym = load_gymnastics()
    artic, w_artic = artic_block(sound, gym)
    isolated, w_iso = isolated_block(sound, gym)
    warnings.extend(w_artic)
    warnings.extend(w_iso)
    # Следим за ЧУЖИМИ звуками — это весь запрет, кроме мягкого близнеца самой
    # цели: «Грибок» = [гр'ибок] несёт р', но это та же фонема, не чужая.
    _watch = banned - {_softness_twin(sound) or ""}
    warnings.extend(_artic_name_notice(artic, _watch, gym, sound))
    warnings.extend(_isolated_notice(isolated, _watch, gym, sound))

    block4 = [it["word"] for g in groups for it in g["items"]]
    content: Dict[str, Any] = {
        "meta": {
            "sound": sound,
            "syl_type": syl_type,
            "profile": sorted(profile),
            "banned": sorted(banned),
            "sheet_no": sheet_no,
            "seed": seed,
            "n_words": found,
            "n_syllables": syllables["n_units"],
            "n_sentences": sentences["n"],
            "source": _words_path(sound, words_path),
        },
        "purity_scope": (
            "фильтр чистоты применён к речевому материалу (слоги · слова · игра · "
            "предложения · чистоговорка); инструкции, названия упражнений, шапка и "
            "подвал под фильтр не подпадают — они навигация, а не материал"
        ),
        # [0] шапка-документ
        "header": {
            "child": child_name,
            "sound_label": f"Звук [{sound.upper()}]",
            "sheet_no": sheet_no,
            "week_from": "", "week_to": "",
            "marks": list(DAYS),
            "signature_label": "Подпись",
        },
        # [1] артикуляционная гимнастика — из gymnastics.json (Фомичёва 1989)
        "artic": artic,
        # [2] изолированный звук — РОВНО ОДНА строка, один игровой образ
        #     (Спивак 2007; постановочные образы отсечены по полю stage)
        "isolated": isolated,
        "syllables": syllables,          # [3]
        "words": {                       # [4]
            "instruction": "Повтори, прочитай слова.",
            "groups": groups,
            "all": block4,
            "n": found,
            "tier_note": "а) короткие частотные · б) длиннее и со стечениями",
        },
        "game": game,                    # [5]
        # Какие из трёх игр на словаре ЭТОГО листа вообще собираются. Нужно
        # экрану: кнопка недоступной игры должна быть погашена ДО нажатия,
        # а не молча подменять выбор логопеда (08-10, по разбору автора).
        "games_offer": games_offer,
        "sentences": sentences,          # [6]
        "fill_syllable": fill,           # [4б] «вставь слог»
        "chistogovorka": chisto,         # [7]
        # [8] графика — сознательно отсутствует в v1
        "footer": list(FOOTER_LINES),    # [9]
        "vocabulary": {
            "verbs": (sentences or {}).get("verbs", []),
            "block4": block4,
            "derived": derived,
            "service": sorted(service),
            "syllables": sorted({u for r in syllables["rows"] for u in r["units"]}
                                | ({chisto["syllable"]} if chisto else set())),
        },
        "warnings": warnings,
    }

    verify_purity(content)               # правила 1-3 — падают, а не молчат
    verify_crosscut(content)             # правило 13
    return content


