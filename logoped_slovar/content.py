@lru_cache(maxsize=8192)
def _analyze(word: str, stress: Optional[int]) -> ph.Analysis:
    """analyze() с запасным ударением на 1-м слоге для производных форм.

    Корректно: ВСЕ корригируемые фонемы — согласные, а согласный состав в
    движке не зависит от места ударения (ударение влияет только на
    реализацию гласных). Инвариант закреплён тестом
    test_purity_is_stress_independent.
    """
    try:
        return ph.analyze(word, stress)
    except ValueError:
        return ph.analyze(word, 1)


def corrigible_of(word: str, stress: Optional[int] = None) -> FrozenSet[str]:
    """Множество корригируемых фонем слова (или бесгласного токена)."""
    if not any(ch in _VOW_LETTERS for ch in word):
        # бесгласный токен («р-р-р» → «р»): буква = твёрдая фонема
        return frozenset(ch for ch in word if ch in ph.CORRIGIBLE)
    return _analyze(word, stress).problem_phonemes


def _softness_twin(target: str) -> Optional[str]:
    base = target.rstrip("'")
    if base in ph.ALWAYS_HARD or base in ph.ALWAYS_SOFT:
        return None
    return base if target.endswith("'") else base + "'"


def banned_phonemes(sound: str, profile: Iterable[str]) -> FrozenSet[str]:
    """Что запрещено на листе = профиль ребёнка (+ мягкие близнецы профиля)
    ∪ смешиваемые с целевым ∪ мягко-твёрдый близнец цели.  Цель — не запрещена.

    Расширение профиля мягкими близнецами сознательное: нарушенный [л] почти
    всегда означает и [л']. Фильтр обязан пере-, а не недо-фильтровывать.
    """
    banned: Set[str] = set()
    for p in profile:
        banned.add(p)
        twin = _softness_twin(p)
        if twin:
            banned.add(twin)
    banned |= set(MIXED_WITH.get(sound, frozenset()))
    for name, a_set, b_set in ph.OPPOSITION_PAIRS:      # оппозиции из движка
        if sound in a_set:
            banned |= set(b_set)
        if sound in b_set:
            banned |= set(a_set)
    twin = _softness_twin(sound)
    if twin:
        banned.add(twin)
    banned.discard(sound)
    return frozenset(banned)


def is_clean(word: str, banned: Iterable[str], stress: Optional[int] = None) -> bool:
    return not (corrigible_of(word, stress) & set(banned))


