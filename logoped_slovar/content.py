def _cons_spans(cl: str) -> List[Tuple[int, int]]:
    """Границы каждого СОГЛАСНОГО в фонемной записи стечения, вместе с его
    апострофом: «р'к» -> [(0, 2), (2, 3)].

    Нужно потому, что мягкий согласный занимает два символа. Пока резали по
    символам, у мягкой цели «стечение» получалось из одного согласного и
    апострофа — и блок печатал «арь · орь · урь», то есть обратный слог под
    заголовком «стечение» (замер 08-08 на р', л', с').
    """
    spans: List[Tuple[int, int]] = []
    i = 0
    while i < len(cl):
        j = i + 1
        if j < len(cl) and cl[j] == "'":
            j += 1
        spans.append((i, j))
        i = j
    return spans


def _n_consonants(frame: str) -> int:
    """Сколько СОГЛАСНЫХ в фонемной записи стечения (апостроф не считается)."""
    return sum(1 for ch in frame if ch != "'" and ch not in "аоуыэи")


def occurrence_kind(occ: Dict[str, Any],
                    vowels: Sequence[str] = VOWELS) -> Set[str]:
    """Каким типам слога отвечает данное вхождение целевого звука.

    `vowels` — ряд ЭТОЙ цели: у твёрдой а-о-у-ы, у мягкой а-о-у-и-э. Без него
    мягкая цель не находила ни одного вхождения: после [л'] стоит «и», а её
    в твёрдом ряду нет.
    """
    kinds: Set[str] = set()
    v_after, v_before = occ["vowel_after"], occ["vowel_before"]
    if occ["in_cluster"]:
        if v_after in vowels and occ["cluster_role"] != "first":
            kinds.add("cluster_onset")            # ТРА: р перед гласной внутри стечения
        if v_before in vowels and occ["cluster_role"] == "first":
            kinds.add("cluster_coda")             # АРТ: р открывает стечение после гласной
        return kinds
    if v_after in vowels:
        kinds.add("direct")                       # РА (в т. ч. в середине слова: коРОва)
        if v_before in vowels:
            kinds.add("intervocal")               # АРА
    elif v_before in vowels:
        kinds.add("reverse")                      # АР
    return kinds


def _group_vowel(occ: Dict[str, Any], syl_type: str,
                 vowels: Sequence[str] = VOWELS) -> Optional[str]:
    """Гласная, по которой слово попадает в колонку блока [4]."""
    if syl_type in ("direct", "intervocal", "cluster_onset"):
        v = occ["vowel_after"]
    else:
        v = occ["vowel_before"]
    return v if v in vowels else None


# ── орфография печати ──────────────────────────────────────────────────
# Внутри всё считается ФОНЕМАМИ: [ш]+[ы] = «шы», и по этой записи ищется
# совпадение с транскрипцией слова. Но на лист печатается то, что взрослый
# ЧИТАЕТ вслух, а «шы» — орфографическая ошибка (правило «жи-ши пиши с И»).
# Поэтому на границе отображения фонемный слог переводится в орфографический.
# Правило узкое и только для непарных твёрдых Ж/Ш: «цы» (огурцы) — законно.
_ORTHO_AFTER_ZH_SH: Dict[str, str] = {"ы": "и", "э": "е"}

# Гласные фонемы (внутренняя запись). «и» и «э» появляются у мягких целей.
_VOWEL_SET: FrozenSet[str] = frozenset("аоуыэи")

# Мягкость парного согласного на письме несёт СЛЕДУЮЩАЯ буква, а не апостроф:
# [л']+[а] пишется «ля», [р']+[о] — «рё». Если гласной нет, мягкость несёт «ь»:
# [а]+[л'] — «аль». Пары ровно те же, что у твёрдого ряда: а↔я, о↔ё, у↔ю, ы↔и.
_IOTATED: Dict[str, str] = {"а": "я", "о": "ё", "у": "ю", "э": "е",
                            "ы": "и", "и": "и"}

# Непарные мягкие (ч, щ, й) уже мягкие сами по себе — йотированная гласная им
# не нужна и была бы ошибкой: школьное правило «ча-ща пиши с А, чу-щу пиши с У».
# Меняются только «о»→«ё» (щётка), «э»→«е» (щенок), «ы»→«и» (щи).
_AFTER_ALWAYS_SOFT: Dict[str, str] = {"о": "ё", "э": "е", "ы": "и"}


def syllable_keeps_sound(sound: str, syllable_ortho: str) -> bool:
    """Уцелел ли ЦЕЛЕВОЙ звук в слоге, который реально попадёт на бумагу.

    Сборка слога наивна — она склеивает звук с гласной и не знает про
    оглушение. У звонких в конце слова оно обязательно: «аж» читается [аш],
    «аз» — [ас]. Значит материал на автоматизацию [Ж] печатал бы [Ш], то есть
    ровно тот звук, от которого ребёнка уводят.

    Лист это ловил всегда (`verify_purity` падает), а дорожки — нет: у них нет
    словесного материала, и проверка чистоты к ним не применялась. Найдено
    2026-08-08 разбором архитектуры; до этого обе дорожки на [ж], [з], [з']
    в обратном слоге печатали чужой звук.

    Правду говорит только настоящий фонетический разбор печатной записи.
    """
    try:
        return sound in ph.analyze(syllable_ortho).transcription
    except Exception:
        return False


def ortho(syl: str) -> str:
    """Фонемная запись слога -> орфографическая (для печати).

    шы -> ши · л'а -> ля · ал' -> аль · ал'а -> аля · що -> щё · тр'а -> тря
    """
    out: List[str] = []
    i, n = 0, len(syl)
    while i < n:
        ch = syl[i]

        # парный мягкий: согласный + апостроф
        if i + 1 < n and syl[i + 1] == "'":
            nxt = syl[i + 2] if i + 2 < n else ""
            out.append(ch)
            if nxt in _VOWEL_SET:
                out.append(_IOTATED.get(nxt, nxt))
                i += 3
            else:
                out.append("ь")            # мягкость без гласной: аль, ось
                i += 2
            continue

        # непарный мягкий (ч, щ, й)
        if ch in ph.ALWAYS_SOFT:
            nxt = syl[i + 1] if i + 1 < n else ""
            out.append(ch)
            if nxt in _VOWEL_SET:
                out.append(_AFTER_ALWAYS_SOFT.get(nxt, nxt))
                i += 2
            else:
                i += 1
            continue

        # непарные твёрдые ж/ш: «жи-ши пиши с И». Для «ц» правило не действует
        # («огурцы» законно), поэтому здесь только ж и ш.
        if ch in ("ж", "ш"):
            nxt = syl[i + 1] if i + 1 < n else ""
            out.append(ch)
            if nxt in _ORTHO_AFTER_ZH_SH:
                out.append(_ORTHO_AFTER_ZH_SH[nxt])
                i += 2
            else:
                i += 1
            continue

        out.append(ch)
        i += 1
    return "".join(out)


def _group_header(sound: str, vowel: str, syl_type: str) -> str:
    if syl_type in ("direct", "intervocal", "cluster_onset"):
        syl = sound + vowel
    else:
        syl = vowel + sound
    return ortho(syl).capitalize() + ":"


def _tier(row: Dict[str, Any], analysis: ph.Analysis, syl_type: str) -> str:
    """Ярус а) короткие частотные · ярус б) длиннее / со стечениями.

    Считаем по слогам и стечениям, а НЕ по номеру типа Марковой: номер типа —
    не шкала сложности (тип 11 «стол, флаг» короче типа 2 «малина»).
    На листе со стечением одно стечение — норма, оно не роняет слово в ярус б.
    """
    allowed_clusters = 1 if syl_type.startswith("cluster") else 0
    if (row.get("familiarity") == 3
            and analysis.n_syllables <= 2
            and len(analysis.clusters) <= allowed_clusters):
        return "а"
    return "б"


def _select_words(sound: str, syl_type: str, banned: FrozenSet[str],
                  rows: Sequence[Dict[str, Any]], n_words: int, sheet_no: int,
                  rnd: random.Random, markova_max: Optional[int],
                  min_familiarity: int) -> Tuple[List[Dict[str, Any]], Dict[str, int]]:
    """Возвращает (сгруппированные колонки, счётчики отсева по воротам)."""
    rejected: Dict[str, int] = {"наличие": 0, "позиция": 0, "структура": 0,
                                "чистота": 0, "частотность": 0, "лексика": 0}
    vowels = vowels_for(sound)          # ряд ЭТОЙ цели: твёрдой или мягкой
    pool: Dict[str, List[Dict[str, Any]]] = {v: [] for v in vowels}

    for row in rows:
        word = row["word"]
        if row.get("sensitive"):
            rejected["лексика"] += 1
            continue
        a = _analyze(word, row.get("stress_syllable"))
        if sound not in a.phoneme_keys:
            rejected["наличие"] += 1
            continue
        occs = [o for o in a.sound_occurrences
                if o["phoneme"] == sound
                and syl_type in occurrence_kind(o, vowels)]
        if not occs:
            rejected["позиция"] += 1
            continue
        if markova_max is not None and (a.markova_v1 is None or a.markova_v1 > markova_max):
            rejected["структура"] += 1
            continue
        if a.problem_phonemes & banned:
            rejected["чистота"] += 1
            continue
        if (row.get("familiarity") or 0) < min_familiarity:
            rejected["частотность"] += 1
            continue
        word_vowels = [v for v in
                       (_group_vowel(o, syl_type, vowels) for o in occs) if v]
        if not word_vowels:
            rejected["позиция"] += 1
            continue
        vowel = word_vowels[0]
        occ = next(o for o in occs
                   if _group_vowel(o, syl_type, vowels) == vowel)
        pool[vowel].append({
            "word": word,
            "stress_syllable": row.get("stress_syllable"),
            "transcription": a.transcription,
            "markova_v1": a.markova_v1,
            "familiarity": row.get("familiarity"),
            "gender": row.get("gender"),
            "plural": row.get("plural"),
            "semantic_category": row.get("semantic_category"),
            "tier": _tier(row, a, syl_type),
            "initial": occ["index"] == 0,
            "stressed": occ["stressed"],
            "_occ": occ,
        })

    # детерминированный порядок внутри колонки
    def rank(item: Dict[str, Any]) -> Tuple[Any, ...]:
        return (
            0 if item["tier"] == "а" else 1,
            0 if item["initial"] else 1,
            0 if item["stressed"] else 1,
            -(item["familiarity"] or 0),
            item["markova_v1"] if item["markova_v1"] is not None else 99,
            item["word"],
        )

    for v in vowels:
        pool[v].sort(key=rank)
        if pool[v]:                                   # лист №N берёт следующий срез
            off = (sheet_no - 1) % len(pool[v])
            pool[v] = pool[v][off:] + pool[v][:off]

    # round-robin по колонкам: колонки наполняются РОВНО, внутри колонки
    # сперва ярус «а», потом «б» (порядок уже задан rank).
    chosen: Dict[str, List[Dict[str, Any]]] = {v: [] for v in vowels}
    queues = {v: list(pool[v]) for v in vowels}
    n_nonempty = sum(1 for v in vowels if queues[v]) or 1
    cap = max(1, -(-n_words // n_nonempty))          # ceil
    taken = 0
    while taken < n_words and any(queues.values()):
        progressed = False
        for v in vowels:
            if taken >= n_words:
                break
            if queues[v] and len(chosen[v]) < cap:
                chosen[v].append(queues[v].pop(0))
                taken += 1
                progressed = True
        if not progressed:
            cap += 1                                  # колонка исчерпалась — добираем из соседних
            if cap > n_words:
                break

    groups: List[Dict[str, Any]] = []
    for v in vowels:
        items = chosen[v]
        if not items:
            continue
        items.sort(key=lambda it: (0 if it["tier"] == "а" else 1, rank(it)))
        groups.append({
            "vowel": v,
            "header": _group_header(sound, v, syl_type),
            "tier_a": [it["word"] for it in items if it["tier"] == "а"],
            "tier_b": [it["word"] for it in items if it["tier"] == "б"],
            "items": items,
        })
    # Остаток колонок отдаём наружу: из него можно доменять одно слово на
    # рифмуемое, если чистоговорке рифмовать не на что (см. _ensure_rhyme).
    return groups, rejected, {v: queues[v] for v in vowels}


def _last_syllable_forms(item: Dict[str, Any]) -> List[Tuple[str, Optional[int], bool]]:
    """Формы слова, годные в рифму: ед. ч. и мн. ч. с ИЗВЕСТНЫМ ударением."""
    out = [(item["word"], item.get("stress_syllable"), False)]
    pl = item.get("plural")
    if pl and pl != item["word"] and pl in PLURAL_STRESS:
        out.append((pl, PLURAL_STRESS[pl], True))
    return out


def _rhymes_on(item: Dict[str, Any], syllables: Sequence[str],
               banned: FrozenSet[str]) -> bool:
    """Может ли это слово закрыть чистоговорку на одном из слогов ряда.

    Мало срифмовать — слово должно ещё встать во фразу. Каркасы «Вот …» и
    «У мамы …» проходят семантические ворота: «Вот усы» отсекается воротами
    категории «тело». Без этой проверки отбор считал лист рифмуемым, а
    чистоговорка всё равно не строилась (поймано на [С]: «усы» на листе есть,
    рифма есть, фразы нет).
    """
    if not (_frame_ok(item, "exist") or _frame_ok(item, "possess")):
        return False
    for form, stress, _ in _last_syllable_forms(item):
        if not is_clean(form, banned, stress):
            continue
        try:
            a = _analyze(form, stress)
        except Exception:
            continue
        if not a.syllables or not a.syllables[-1]["stressed"]:
            continue
        if any(a.transcription.endswith(s) for s in syllables):
            return True
    return False


def _ensure_rhyme(groups: List[Dict[str, Any]], leftovers: Dict[str, List[Dict[str, Any]]],
                  syllables: Sequence[str], banned: FrozenSet[str],
                  warnings: List[str]) -> None:
    """Если рифмовать не на что — меняем ОДНО слово на рифмуемое.

    Канон сквозного словаря (правило 13) требует, чтобы слово чистоговорки
    пришло из блока [4]. Отбор в блок [4] ранжирует слова по канону — ярус,
    позиция, ударность, частотность — и рифмуемость в этом ранге не участвует.
    Из-за этого «часы» и «трусы» лежали в картотеке [С] годными в рифму и на
    лист не попадали (замер 08-08: чистоговорка 12 листов из 19).

    Меняем, а не добавляем: число слов на листе не меняется, правило 11
    (слоговой блок ≤ ¼ словесного) не сдвигается. Жертвуем САМЫМ НИЗКИМ
    в ранге словом той же колонки — оно последнее в списке.
    """
    if any(_rhymes_on(it, syllables, banned) for g in groups for it in g["items"]):
        return
    for g in groups:
        for cand in leftovers.get(g["vowel"], []):
            if not _rhymes_on(cand, syllables, banned):
                continue
            victim = g["items"][-1]
            g["items"][-1] = cand
            g["tier_a"] = [it["word"] for it in g["items"] if it["tier"] == "а"]
            g["tier_b"] = [it["word"] for it in g["items"] if it["tier"] == "б"]
            warnings.append(
                f"ради чистоговорки слово «{victim['word']}» заменено на "
                f"«{cand['word']}»: рифмовать было не на что, а канон требует "
                f"брать слово чистоговорки из блока слов")
            return


def _shortfall_message(found: int, requested: int, rejected: Dict[str, int],
                       markova_max: Optional[int], min_familiarity: int) -> str:
    hints: List[str] = []
    if rejected.get("структура"):
        cap = (markova_max or 4) + 2
        hints.append(f"разрешить тип Марковой до {cap} (отсеяно {rejected['структура']})")
    if rejected.get("частотность"):
        hints.append(f"снять требование familiarity={min_familiarity} "
                     f"(отсеяно {rejected['частотность']})")
    if rejected.get("позиция"):
        hints.append(f"взять другой тип слога — в этой позиции слов мало "
                     f"(отсеяно {rejected['позиция']})")
    if rejected.get("чистота"):
        hints.append(f"чистоту снимать НЕЛЬЗЯ (отсеяно {rejected['чистота']}) — "
                     f"нужен более широкий словарь")
    tail = "; расширить: " + " / ".join(hints) if hints else ""
    return f"нашлось {found} слов из {requested}{tail}"


