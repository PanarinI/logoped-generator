def _syllable_text(sound: str, vowel: str, syl_type: str, frame: str = "") -> str:
    if syl_type == "direct":
        return sound + vowel
    if syl_type == "reverse":
        return vowel + sound
    if syl_type == "intervocal":
        return vowel + sound + vowel
    if syl_type == "cluster_onset":
        return frame + vowel
    if syl_type == "cluster_coda":
        return vowel + frame
    raise ContentError(f"неизвестный тип слога: {syl_type!r}")


_ROLE_INDEX: Dict[str, int] = {"first": 0, "second": 1, "third": 2,
                               "fourth": 3, "fifth": 4}


# Стечения, которые при чтении ВСЛУХ сливаются в другую фонему. В слове это
# норма («подсолнух» = [патсолнух]), но вынесенное в слоговой ряд «тса-тсо-тсу»
# читается как [ца-цо-цу] — то есть на лист [с] попадает оппозиционный [ц],
# и фильтр чистоты этого не видит: он разбирает «тса» побуквенно.
# Поймано на реальном листе с/cluster_onset (единственный источник — «подсолнух»).
_FUSING_PAIRS: Tuple[str, ...] = ("тс", "дс", "тц", "дц", "тч", "дч",
                                  "сч", "зч", "сш", "зш", "сж", "зж", "жж", "сс")


def _fuses(frame: str) -> Optional[str]:
    for p in _FUSING_PAIRS:
        if p in frame:
            return p
    return None


def _cluster_frames(groups: Sequence[Dict[str, Any]], syl_type: str,
                    limit: int, warnings: Optional[List[str]] = None) -> List[str]:
    """Стечения берём из ОТОБРАННЫХ слов — тогда связка «слог — слово» существует.

    Стечение обрезается до слоговой единицы: для ТРА — от начала стечения до
    целевого звука включительно (стр-, тр-, кр-), для АРТ — целевой звук плюс
    ОДИН согласный. Иначе из «отвёртки» ([-ртк-], стечение через границу слога)
    получается небывалый слог «ыртк».

    Сливающиеся стечения (тс, сч, зж…) в слоговой ряд не выпускаются — см.
    _FUSING_PAIRS. Слово с таким стечением остаётся в блоке [4]: там оно звучит
    нормально, потому что произносится целиком.
    """
    counts: Dict[str, int] = {}
    dropped: Dict[str, str] = {}
    for g in groups:
        for it in g["items"]:
            occ = it["_occ"]
            cl = occ["cluster"]
            if not cl:
                continue
            i = _ROLE_INDEX.get(occ["cluster_role"] or "", 0)
            spans = _cons_spans(cl)
            if i >= len(spans):
                continue
            if syl_type == "cluster_onset":
                frame = cl[:spans[i][1]]                    # от начала до цели включительно
            else:
                if i + 1 >= len(spans):
                    continue                               # второго согласного нет
                frame = cl[spans[i][0]:spans[i + 1][1]]     # цель + следующий согласный
            # Стечение — это ДВА СОГЛАСНЫХ, а не два символа.
            if _n_consonants(frame) < 2 or _n_consonants(frame) > 3:
                continue
            fuse = _fuses(frame)
            if fuse:
                dropped[frame] = fuse
                continue
            counts[frame] = counts.get(frame, 0) + 1
    if dropped and warnings is not None:
        warnings.append(
            "слоговые ряды сняты — стечение при чтении сливается в другой звук: "
            + " · ".join(f"«{f}» ({p} → аффриката/долгий)" for f, p in sorted(dropped.items()))
            + "; слова с ним остались в блоке [4], там они звучат нормально")
    return sorted(counts, key=lambda c: (-counts[c], len(c), c))[:limit]


def _bond_place(word: str, syllable: str, syl_type: str) -> int:
    """0 — слог стоит в слове ТАМ ЖЕ, где отрабатывается; 1 — просто внутри.

    Связка «слог — слово» существует, чтобы ребёнок услышал ТОТ ЖЕ слог в том же
    месте: для прямого — в начале (ра — рак), для обратного — в конце
    (ар — комар). «гра — виноград» формально верно, но слог спрятан в середине —
    берём такое только когда лучшего нет.
    """
    if syl_type in ("direct", "cluster_onset"):
        return 0 if word.startswith(syllable) else 1
    if syl_type in ("reverse", "cluster_coda"):
        return 0 if word.endswith(syllable) else 1
    return 0 if syllable in word else 1


def _find_bond(syllable: str, groups: Sequence[Dict[str, Any]],
               used: Set[str], avoid_used: bool = True,
               syl_type: str = "direct") -> Optional[str]:
    """Слово из блока [4] под связку «слог — слово».

    Совпадение по ЗВУЧАНИЮ обязательно (ребёнок произносит, а не читает):
    «борода» = [барада] на слог «оро» НЕ годится, хотя буквы совпадают.
    Совпадение по буквам — только приоритет внутри звучащих кандидатов, чтобы
    родителю не подсовывать «ра — розетка».
    """
    best: Optional[Tuple[Any, ...]] = None
    for g in groups:
        for it in g["items"]:
            w, tr = it["word"], it["transcription"]
            if syllable not in tr:
                continue                       # ворота: только по звукам
            if avoid_used and w in used:
                continue
            # длина — тай-брейк: связка это ПЕРВОЕ слово на этом слоге, короткое
            # легче; заодно слоговой ряд остаётся в полстроки и блок [3] не
            # разбухает (правило 11). Жёсткие ворота выше этим не трогаются.
            key = (1 if w in used else 0, _bond_place(w, syllable, syl_type),
                   0 if tr.startswith(syllable) else 1, len(w), w)
            if best is None or key < best:
                best = key
    return best[-1] if best else None


def _build_syllables(sound: str, syl_type: str, groups: Sequence[Dict[str, Any]],
                     n_words: int, rnd: random.Random,
                     warnings: List[str]) -> Dict[str, Any]:
    # правило 11: слоговой блок ≤ ¼ словесного. Мера — СТРОКИ: слоговой ряд = 1
    # строка, слово в колонке = 1 строка. 4 ряда × 4 гласных = 16 единиц при 16
    # словах — ровно ¼. Минимум по скелету — 16 единиц (4 ряда), поэтому при
    # словаре меньше 16 слов правила спорят, и мы говорим об этом вслух.
    max_rows_by_volume = max(1, n_words // 4)
    n_rows = min(6, max(4, max_rows_by_volume))
    if n_rows > max_rows_by_volume:
        warnings.append(
            f"слоговой блок {n_rows} рядов при {n_words} словах: скелет требует "
            f"минимум 16 слогов (4 ряда), правило 11 (≤ ¼ словесного) при таком "
            f"словаре не выполняется — доберите слова до 16"
        )

    rows: List[Dict[str, Any]] = []
    if syl_type in ("cluster_onset", "cluster_coda"):
        frames = _cluster_frames(groups, syl_type, n_rows, warnings)
        if not frames:
            raise ContentError(
                f"тип слога {syl_type!r}: в отобранных словах нет стечений — "
                f"связку «слог — слово» построить не из чего"
            )
        syl_vowels = syl_vowels_for(sound)
        for frame in frames:
            units = [_syllable_text(sound, v, syl_type, frame)
                     for v in syl_vowels]
            rows.append({"units": units})
    else:
        syl_vowels = syl_vowels_for(sound)
        for i in range(n_rows):
            order = [syl_vowels[(i + k) % len(syl_vowels)]
                     for k in range(len(syl_vowels))]
            units = [_syllable_text(sound, v, syl_type) for v in order]
            rows.append({"units": units})

    out_rows: List[Dict[str, Any]] = []
    used_bonds: Set[str] = set()
    for row in rows:
        bond = None
        # правило 7: ряд без связки не выпускаем. Сперва ищем слово, ещё не
        # занятое другим рядом, и только потом разрешаем повтор.
        # Связка по умолчанию — на ВЕДУЩУЮ единицу ряда: ряд «ра ро ру ры»
        # замыкается на «ра — рак», и за 4 ряда каждый слог получает своё слово.
        # Но если ведущая единица даёт слово со спрятанным слогом («гра —
        # виноград»), берём лучшую единицу ряда: «гру — грузовик» — слог на
        # своём месте. Порядок: сперва слово, ещё не занятое другим рядом.
        for avoid in (True, False):
            cands = []
            for i, unit in enumerate(row["units"]):
                word = _find_bond(unit, groups, used_bonds, avoid_used=avoid,
                                  syl_type=syl_type)
                if word:
                    cands.append((_bond_place(word, unit, syl_type), i,
                                  len(word), unit, word))
            if not cands:
                continue
            lead = next((c for c in cands if c[1] == 0 and c[0] == 0), None)
            best = lead or min(cands)
            bond = {"syllable": best[3], "word": best[4]}
            used_bonds.add(best[4])
            break
        if bond is None:
            warnings.append(
                f"ряд {' — '.join(row['units'])} снят: нет слова для связки "
                f"«слог — слово» (правило 7)"
            )
            continue
        # units — фонемные (по ним искалась связка); наружу отдаём орфографию
        units_display = [ortho(u) for u in row["units"]]
        bond_display = {"syllable": ortho(bond["syllable"]),
                        "syllable_phon": bond["syllable"],
                        "word": bond["word"]}
        out_rows.append({
            "units": units_display,
            "units_phon": list(row["units"]),
            "bond": bond_display,
            "text": " — ".join(units_display)
                    + f"      {bond_display['syllable']} — {bond['word']}",
        })

    if not out_rows:
        raise ContentError("слоговой блок пуст: ни одного ряда со связкой «слог — слово»")

    n_units = sum(len(r["units"]) for r in out_rows)
    if n_units < 16:
        warnings.append(f"слогов {n_units} — меньше канонических 16 (рядов не хватило)")
    return {
        "type": syl_type,
        "type_label": SYL_TYPE_LABEL[syl_type],
        "instruction": "Повтори, прочитай слоги.",
        "rows": out_rows,
        "n_units": n_units,
        "n_rows": len(out_rows),
    }


