def _countable(item: Dict[str, Any]) -> bool:
    """Годится ли слово для игры «Один — много».

    ⚠ 2026-08-24, поймал автор на слове «лёд». Проверка стояла на одном
    признаке — «форма множественного существует и слово не среднего рода», — а
    игра держится на ДРУГОМ: предмет должен быть СЧЁТНЫМ. Этого признака в
    данных не было вовсе, и на лист [Ль] выходило «лёд ___», где ответ «льды»
    означает ледяные поля, а не «много льда».

    Ровно локальный закон 7: правило врёт, работает таблица. Форма мн. ч. в
    русском есть почти у всего, но у вещественных она даёт СОРТА (соки, каши,
    колбасы), у омонимов — другое слово («душ» → «души» от «душа»), у омографов
    — другое ударение («замок» → за́мки и замки́).

    Поэтому счётность размечается РУКАМИ в карточке полем `countable: false`.
    Размечено 14 слов — те, что реально доходили до игры. Полная разметка всех
    существительных с `plural` стоит отдельной работы двойным разбором, как
    делали падежи (развилка записана в STATE).
    """
    if item.get("countable") is False:
        return False
    pl = item.get("plural")
    return bool(pl) and pl != item["word"] and item.get("gender") in ("m", "f", "n")


def _game_one_many(items: Sequence[Dict[str, Any]], banned: FrozenSet[str],
                   derived: Dict[str, str],
                   stat: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    pairs: List[Dict[str, str]] = []
    for it in items:
        if not _countable(it):
            continue
        pl = it["plural"]
        if not is_clean(pl, banned):
            continue
        pairs.append({"prompt": it["word"], "answer": pl})
    if stat is not None:
        stat["found"] = len(pairs)
    if len(pairs) < 4:
        return None
    for p in pairs:
        derived[p["answer"]] = p["prompt"]
    return {
        "kind": "one_many",
        "title": "Один — много",
        "instruction": "Назови много.",
        "sample": f"Образец: {pairs[0]['prompt']} — {pairs[0]['answer']}.",
        "items": pairs,
    }


def _game_diminutive(items: Sequence[Dict[str, Any]], banned: FrozenSet[str],
                     derived: Dict[str, str], notes: List[str],
                     allow_rule: bool,
                     stat: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    pairs: List[Dict[str, Any]] = []
    blocked: List[str] = []
    for it in items:
        w = it["word"]
        if w in DIMINUTIVE_BLOCKED:
            blocked.append(f"{w} ({DIMINUTIVE_BLOCKED[w]})")
            continue
        form, source = DIMINUTIVE.get(w), "таблица"
        if form is None and allow_rule:
            form, source = _rule_diminutive(w, it.get("gender")), "правило (не выверено)"
        if form is None:
            blocked.append(f"{w} (деминутив не задан)")
            continue
        if not is_clean(form, banned):
            blocked.append(f"{w} → {form} — грязно по профилю")
            continue
        pairs.append({"prompt": w, "answer": form, "source": source})
    if blocked:
        notes.append("деминутив невозможен/не задан: " + ", ".join(blocked))
    if stat is not None:
        stat["found"] = len(pairs)
    if len(pairs) < 4:
        return None
    for p in pairs:
        derived[p["answer"]] = p["prompt"]
    return {
        "kind": "diminutive",
        "title": "Назови ласково",
        "instruction": "Назови ласково.",
        "sample": f"Образец: {pairs[0]['prompt']} — {pairs[0]['answer']}.",
        "items": pairs,
    }


def _game_count(items: Sequence[Dict[str, Any]], banned: FrozenSet[str],
                derived: Dict[str, str],
                service: Dict[str, int],
                stat: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    # числительные — тоже речевой материал: если хоть одно не прошло фильтр
    # профиля, игру не строим (лучше другая игра, чем грязная строка)
    if not {"один", "одна", "одно", "два", "две", "пять"} <= set(service):
        if stat is not None:
            stat["reason"] = "numerals"
        return None
    rows: List[Dict[str, Any]] = []
    for it in items:
        if not _countable(it):
            continue
        w, g = it["word"], it["gender"]
        gs, gp = _gen_sg(w, g), _gen_pl(w, g)
        if not gs or not gp:
            continue
        if not (is_clean(gs, banned) and is_clean(gp, banned)):
            continue
        one = {"m": "один", "f": "одна", "n": "одно"}[g]
        two = "две" if g == "f" else "два"
        rows.append({
            "prompt": w,
            "forms": [f"{one} {w}", f"{two} {gs}", f"пять {gp}"],
            "answer": f"{one} {w} — {two} {gs} — пять {gp}",
        })
    if stat is not None:
        stat["found"] = len(rows)
    if len(rows) < 4:
        return None
    for r in rows:
        derived[r["answer"].split(" — ")[1].split()[-1]] = r["prompt"]
        derived[r["answer"].split(" — ")[2].split()[-1]] = r["prompt"]
    return {
        "kind": "count_1_5",
        "title": "Посчитай 1-5",
        "instruction": "Назови по образцу.",
        "sample": f"Образец: {rows[0]['answer']}.",
        "items": rows,
    }


def _build_game(groups: Sequence[Dict[str, Any]], banned: FrozenSet[str],
                seed: int, sheet_no: int, derived: Dict[str, str],
                warnings: List[str], allow_rule_diminutive: bool,
                service: Dict[str, int],
                n_items: int = 6,
                want: str = "",
                offer: Optional[Dict[str, Dict[str, Any]]] = None,
                ) -> Optional[Dict[str, Any]]:
    """Грамматическая игра блока [5].

    Все три игры канонные — ТЗ, ЯРУС А: «один-много» · «назови ласково» ·
    «посчитай 1-5». Раньше выбор делал только сид, и логопед повлиять не мог;
    с 2026-08-09 он может назвать игру (`want`), а движок честно откатится к
    другой, если на словаре ЭТОГО листа выбранная не набирает четырёх примеров,
    и скажет об этом вслух. Молча подменять выбор логопеда нельзя.

    2026-08-10. Пробуем ВСЕ три, а не до первой удачной, и складываем итог в
    `offer`. Причина не в движке, а на экране: кнопки игр там были активны
    всегда, и на листе, где выбранная игра не набирается, логопед жал «Назови
    ласково» и получал молча ту же «Один — много». Экран не может показать
    честные кнопки, пока движок не скажет, какие игры на ЭТОМ словаре живые.
    Перебор дешёвый: игры собираются из уже отобранных слов блока [4].
    """
    items = [it for g in groups for it in g["items"]]
    built: Dict[str, Optional[Dict[str, Any]]] = {}
    made: Dict[str, Dict[str, Any]] = {}     # kind → {derived, notes, stat}
    for kind in GAME_KINDS:
        local_derived: Dict[str, str] = {}
        local_notes: List[str] = []
        stat: Dict[str, Any] = {}
        if kind == "one_many":
            game = _game_one_many(items, banned, local_derived, stat)
        elif kind == "diminutive":
            game = _game_diminutive(items, banned, local_derived, local_notes,
                                    allow_rule_diminutive, stat)
        else:
            game = _game_count(items, banned, local_derived, service, stat)
        built[kind] = game
        made[kind] = {"derived": local_derived, "notes": local_notes,
                      "stat": stat}
        if offer is not None:
            # Наружу идут ФАКТЫ, а не готовая фраза: человеческий текст —
            # дом web/human.py (локальный закон 3), здесь он был бы вторым
            # источником правды для одного и того же.
            offer[kind] = {"ok": game is not None,
                           "found": int(stat.get("found", 0)),
                           "need": 4,
                           "reason": str(stat.get("reason", ""))}

    order = [GAME_KINDS[(seed + sheet_no - 1 + i) % len(GAME_KINDS)]
             for i in range(len(GAME_KINDS))]
    if want in GAME_KINDS:
        order = [want] + [k for k in order if k != want]
    tried: List[str] = []
    for kind in order:
        game = built[kind]
        if game is not None:
            if tried:
                why = ("выбранная логопедом игра" if want and tried[0] == want
                       else f"игра {tried[0]!r}")
                warnings.append(
                    f"игра «{kind}» выбрана вместо {tried[0]!r}: {why} на словаре "
                    f"этого листа набрала меньше 4 примеров"
                )
            game["items"] = game["items"][:n_items]
            keep = {i["answer"] for i in game["items"]}
            for form, lemma in made[kind]["derived"].items():
                if any(form in a for a in keep):
                    derived[form] = lemma
            game["items_to_do"] = game["items"][1:]
            game["notes"] = made[kind]["notes"]
            return game
        tried.append(kind)
    notes = [n for k in GAME_KINDS for n in made[k]["notes"]]
    warnings.append(
        "блок [5] пуст: ни одна из трёх грамматических игр не набрала 4 примера "
        f"на словаре этого листа ({len(items)} слов). Проверены: "
        + ", ".join(tried) + ". "
        + (" ".join(notes) + " " if notes else "")
        + "Расширить: увеличить n_words, сменить тип слога или пополнить словарь."
    )
    return None


