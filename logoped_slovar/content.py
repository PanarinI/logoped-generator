def render_preview(c: Dict[str, Any]) -> str:
    m = c["meta"]
    L: List[str] = []
    L.append("═" * 66)
    L.append(f"[0] Ребёнок ______  ·  {c['header']['sound_label']}  ·  "
             f"Лист № {m['sheet_no']}  ·  неделя с ___ по ___")
    L.append("    отметки: " + "  ".join(f"{d}[ ]" for d in c["header"]["marks"])
             + "     Подпись ________")
    L.append("─" * 66)
    L.append(f"[1] {c['artic']['instruction']}  ({c['artic']['time_note']})")
    L.append("    " + "   ".join(f"{n} [ ]" for n in c["artic"]["items"]))
    L.append(f"    {c['artic']['note']}")
    L.append("─" * 66)
    L.append(f"[2] {c['isolated']['line']}")
    L.append("─" * 66)
    s = c["syllables"]
    L.append(f"[3] {s['instruction']}   ({s['type_label']}, {s['n_units']} слогов)")
    for row in s["rows"]:
        L.append("    " + row["text"])
    L.append("─" * 66)
    w = c["words"]
    L.append(f"[4] {w['instruction']}   ({w['n']} слов)")
    for g in w["groups"]:
        L.append(f"    {g['header']}")
        if g["tier_a"]:
            L.append("      а) " + ", ".join(g["tier_a"]))
        if g["tier_b"]:
            L.append("      б) " + ", ".join(g["tier_b"]))
    L.append("─" * 66)
    g = c["game"]
    if g:
        L.append(f"[5] {g['title']}. {g['instruction']}")
        L.append(f"    {g['sample']}")
        if g["kind"] == "count_1_5":
            for it in g["items_to_do"]:
                L.append(f"    {it['prompt']} — … — …")
        else:
            L.append("    " + ",  ".join(f"{it['prompt']} — …" for it in g["items_to_do"]))
    else:
        L.append("[5] игра не построена (см. warnings)")
    L.append("─" * 66)
    L.append(f"[6] {c['sentences']['instruction']}")
    last = None
    for it in c["sentences"]["items"]:
        if it["scale"] != last:
            L.append(f"    {it['scale']}:")
            last = it["scale"]
        L.append(f"      {it['text']}")
    L.append("─" * 66)
    if c["chistogovorka"]:
        L.append(f"[7] {c['chistogovorka']['instruction']}")
        L.append(f"    {c['chistogovorka']['text']}")
    else:
        L.append("[7] чистоговорка не построена (см. warnings)")
    L.append("─" * 66)
    L.append("[9] " + "  ".join(c["footer"][:1]))
    for line in c["footer"][1:]:
        L.append("    " + line)
    L.append("═" * 66)
    if c["warnings"]:
        L.append("ПРЕДУПРЕЖДЕНИЯ:")
        for wn in c["warnings"]:
            L.append("  ! " + wn)
    return "\n".join(L)


