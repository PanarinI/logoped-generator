# Гласные, допустимые рядом с твёрдым звуком. И — исключена: даёт мягкий Рь.
#
# ДВА РАЗНЫХ СПИСКА, и это не дублирование.
# VOWELS — для КОЛОНОК СЛОВ (блок [4]): колонка существует, только если под неё
#   есть слова. Слогов «рэ» и «сэ» в русской детской лексике нет (в наших
#   картотеках — ноль слов; в языке они живут почти только в заимствованиях:
#   рэп, рэкет). Колонка «Рэ:» была бы всегда пустой.
# SYL_VOWELS — для СЛОГОВОГО РЯДА (блок [3]): слог произносят, ему слово не
#   нужно. Канон-сверка проекта прямо разрешает Э («после звука — только А О У Ы
#   (+Э)»), и на образце звуковой дорожки, присланном логопедом Ольгой
#   Субботиной, стоит ровно пятёрка РА · РО · РУ · РЫ · РЭ (см. ГОЛОСА.md).
#   Раньше Э выпадала молча: комментарий объяснял только исключение И.
# ⚡ Э ЗАКОННА, НО НА ЛИСТ ПОКА НЕ ВСТАЁТ — И ЭТО ИЗМЕРЕНО, А НЕ МНЕНИЕ.
# Прогон 45 сочетаний (3 звука × 5 типов × 3 профиля) с пятой гласной и без:
# с Э канон-линтер ловит 30 нарушений вместо 24. Хуже стало в 6 случаях,
# лучше — ни в одном. Среди испорченных базовый [Ш] + прямые слоги.
# Причина механическая: пятая единица растит слоговой блок на четверть, и он
# перестаёт помещаться в канонное правило 11 («слоговой блок ≤ ¼ словесного»).
# То есть конфликтуют два канонных требования, а не «Ольга против нас»:
# её образец — ЗВУКОВАЯ ДОРОЖКА, там слоги живут без слов и правило 11 не
# работает. Значит РЭ — законный слог дорожки, и когда дорожку построим, он
# там будет обязателен. Решение по листу — за автором (см. DECISIONS 08-03).
VOWELS: Tuple[str, ...] = ("а", "о", "у", "ы")
SYL_VOWELS: Tuple[str, ...] = ("а", "о", "у", "ы")

# ── МЯГКАЯ ЦЕЛЬ: другой ряд гласных, и это не наша выдумка ──────────────
# Мягкость согласного в русском создают передние гласные. Ряд «а о у ы»
# принадлежит ТВЁРДОМУ звуку: слог «ла» — это [л], а не [л'], и фильтр
# чистоты справедливо ронял сборку мягкой цели на первом же слоге.
# Фонемные пары: а↔я, о↔ё, у↔ю, ы↔и. Плюс э (пишется «е»).
#
# ⚡ Пятая гласная здесь не роскошь, а основной материал — ИЗМЕРЕНО по нашим
# же словарям (число вхождений после целевого звука):
#     [л'] и 56 · э 24 · о 13 · у 12 · а 7
#     [р'] и 73 · э 36 · о 11 · а 8  · у 5
#     [щ]  и 68 · о 12 · э 10 · у 3  · а 2
# То есть у мягких «и» и «э» — первые две по частоте («лиса», «лес», «река»),
# тогда как у твёрдых «э» почти пуста (рэп, рэкет — не детская лексика).
# Поэтому КОЛОНКИ СЛОВ мягкой цели берут пять гласных, а СЛОГОВОЙ РЯД — четыре:
# пятая единица растит слоговой блок на четверть и ломает канонное правило 11
# («слоговой блок ≤ ¼ словесного») — это уже было измерено на [Э] у твёрдых.
VOWELS_SOFT: Tuple[str, ...] = ("а", "о", "у", "и", "э")
SYL_VOWELS_SOFT: Tuple[str, ...] = ("а", "о", "у", "и")


def is_soft_target(sound: str) -> bool:
    """Мягкая ли цель: парный мягкий (р', л', с', з') или непарный (ч, щ, й)."""
    return sound.endswith("'") or sound in ph.ALWAYS_SOFT


def vowels_for(sound: str) -> Tuple[str, ...]:
    """Гласные КОЛОНОК СЛОВ (блок [4]) для этой цели."""
    return VOWELS_SOFT if is_soft_target(sound) else VOWELS


def syl_vowels_for(sound: str) -> Tuple[str, ...]:
    """Гласные СЛОГОВОГО РЯДА (блок [3]) для этой цели."""
    return SYL_VOWELS_SOFT if is_soft_target(sound) else SYL_VOWELS
