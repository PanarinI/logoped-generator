# Шаблоны строго в ИМЕНИТЕЛЬНОМ падеже — падежное согласование в v1 не
# генерируется (лучше беднее, чем с грамматической ошибкой).
# Второй элемент — каркас: "exist" (бытийный: Тут/Вот) или "possess"
# (принадлежность: У мамы / дома). Каркас режет бессмыслицу вида
# «Дома одна рука» и «У папы нора».
# ⚠ КАНОННАЯ НОРМА, которой мы пока НЕ соответствуем (найдена проверкой 08-06):
#   «Желательно, чтобы в каждом слове, входящем в предложение, был
#    автоматизируемый звук и отсутствовали неправильно произносимые ребёнком
#    звуки» — Фомичёва М. Ф., 1989, с. 39.
# У нас половина предложения — служебные слова БЕЗ целевого звука («У мамы дома
# бронза» = звук в одном слове из четырёх). Полностью выполнить норму нельзя:
# каркас обязан быть из чистых служебных слов, иначе на лист [Р] полезет «около»
# с [л]. Но плотность повышается тем, что каркасы с ДВУМЯ и ТРЕМЯ словарными
# слотами предпочтительнее односложных — это учтено в порядке ниже.
#
# Набор расширен 08-06: было 12 каркасов на все одиннадцать звуков, и лист
# читался под копирку («Тут бронза и рюкзак» · «Вот бальзам, вот линза»).
# Ограничения не сняты, а обойдены изнутри: только именительный падеж (падежное
# согласование не генерируется — лучше беднее, чем с ошибкой) и только слова из
# SERVICE_WORDS, каждое из которых само прошло фильтр чистоты.
SENTENCE_TEMPLATES: Dict[int, Tuple[Tuple[str, str], ...]] = {
    3: (("У мамы {n1}.", "possess"), ("У папы {n1}.", "possess"),
        ("Вот тут {n1}.", "exist"), ("Тут {one} {n1}.", "exist"),
        ("Вот это {n1}.", "exist"), ("Там {one} {n1}.", "exist"),
        ("А тут {n1}.", "exist"), ("Дома {one} {n1}.", "possess")),
    4: (("Тут {n1} и {n2}.", "exist"), ("Вот {n1}, вот {n2}.", "exist"),
        ("У мамы дома {n1}.", "possess"), ("У папы дома {n1}.", "possess"),
        ("Там {n1} и {n2}.", "exist"), ("Это {n1} и {n2}.", "exist"),
        ("Дома {n1} и {n2}.", "possess"), ("Вот {n1} и {n2}.", "exist")),
    5: (("Тут {n1}, {n2} и {n3}.", "exist"), ("Вот {n1}, {n2} и {n3}.", "exist"),
        ("У мамы {n1} и {n2}.", "possess"), ("Дома {n1}, {n2} и {n3}.", "possess"),
        ("Тут {n1}, а тут {n2}.", "exist"), ("Там {n1}, {n2} и {n3}.", "exist"),
        ("Это {n1}, {n2} и {n3}.", "exist"), ("У папы {n1} и {n2}.", "possess")),
}

# Семантические ворота каркасов. Смысл не вычисляется — берётся из поля
# semantic_category словаря; это грубо, но честно и проверяемо.
SENTENCE_BAN: Tuple[str, ...] = (
    "тело", "животные/части", "одежда/части", "растения/части", "дом/части",
    "природа/явления", "животные/уход",
)
POSSESS_OK: Tuple[str, ...] = (
    "дом/предметы", "дом/посуда", "дом/техника", "еда", "одежда", "предметы",
    "игрушки", "школа", "музыка", "инструменты", "мебель", "транспорт",
    "фигуры", "техника", "животные/домашние",
)


def _frame_ok(item: Dict[str, Any], frame: str) -> bool:
    cat = item.get("semantic_category") or ""
    if cat.startswith(SENTENCE_BAN):
        return False
    if frame == "possess":
        return cat.startswith(POSSESS_OK)
    return True

_TOKEN_RE = re.compile(r"[а-яё]+")


def _tokens(text: str) -> List[str]:
    return _TOKEN_RE.findall(text.lower())


def _service_pool(sound: str, banned: FrozenSet[str]) -> Dict[str, int]:
    """Служебные слова, прошедшие фильтр: чисто по профилю И без целевого звука."""
    out: Dict[str, int] = {}
    for w, stress in SERVICE_WORDS:
        a = _analyze(w, stress)
        if a.problem_phonemes & banned:
            continue
        if sound in a.phoneme_keys:       # слово с целевым звуком обязано быть в блоке [4]
            continue
        out[w] = stress
    return out


def _build_sentences(groups: Sequence[Dict[str, Any]], sound: str,
                     banned: FrozenSet[str], service: Dict[str, int],
                     rnd: random.Random, n_sentences: int,
                     warnings: List[str]) -> Dict[str, Any]:
    items = [it for g in groups for it in g["items"]]
    if not items:
        raise ContentError("предложения строить не из чего: блок [4] пуст")

    pools: Dict[str, List[Dict[str, Any]]] = {
        frame: [it for it in items if _frame_ok(it, frame)]
        for frame in ("exist", "possess")
    }
    tiebreak: Dict[str, float] = {it["word"]: rnd.random() for it in items}
    used: Dict[str, int] = {}

    def take(k: int, frame: str) -> List[Dict[str, Any]]:
        """Наименее использованные слова — чтобы лист не крутил одно и то же."""
        ordered = sorted(pools[frame],
                         key=lambda it: (used.get(it["word"], 0), tiebreak[it["word"]]))
        out = ordered[:k]
        for it in out:
            used[it["word"]] = used.get(it["word"], 0) + 1
        return out

    plan = [3] * 3 + [4] * 3 + [5] * max(0, n_sentences - 6)
    plan = plan[:n_sentences]

    sentences: List[Dict[str, Any]] = []
    used_templates: Set[str] = set()
    for want in plan:
        templates = [(t, f) for t, f in SENTENCE_TEMPLATES[want]
                     if _template_ok(t, service) and len(pools[f]) >= 1]
        if not templates:
            warnings.append(f"нет пригодного шаблона для предложения из {want} слов")
            continue
        fresh = [tf for tf in templates if tf[0] not in used_templates] or templates
        tpl, frame = fresh[rnd.randrange(len(fresh))]
        used_templates.add(tpl)

        need = sum(1 for k in ("{n1}", "{n2}", "{n3}") if k in tpl)
        nouns = take(need, frame)
        if len(nouns) < need:
            warnings.append(
                f"предложение из {want} слов не собрано: в блоке [4] меньше {need} "
                f"слов, подходящих каркасу «{frame}»")
            continue
        fill: Dict[str, str] = {f"n{i+1}": nouns[i]["word"] for i in range(need)}
        if "{one}" in tpl:
            g = nouns[0].get("gender")
            if g not in ("m", "f", "n"):
                continue
            fill["one"] = {"m": "один", "f": "одна", "n": "одно"}[g]
        text = tpl.format(**fill)
        n_tokens = len(text.split())
        if n_tokens != want:                       # самопроверка шкалы длины
            raise ContentError(f"шаблон {tpl!r} дал {n_tokens} слов вместо {want}")
        sentences.append({"text": text, "n_words": want,
                          "scale": {3: "Три слова", 4: "Четыре слова",
                                    5: "Пять слов"}[want]})

    if len(sentences) < 6:
        warnings.append(f"предложений {len(sentences)} — меньше канонических 6")
    return {
        "instruction": "Повтори, прочитай предложения.",
        "items": sentences,
        "n": len(sentences),
    }


def _template_ok(template: str, service: Dict[str, int]) -> bool:
    """Все НЕслотовые слова шаблона обязаны быть в допущенном служебном пуле."""
    skeleton = re.sub(r"\{[a-z0-9]+\}", " ", template)
    for tok in _tokens(skeleton):
        if tok not in service:
            return False
    return True


