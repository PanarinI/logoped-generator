@lru_cache(maxsize=1)
def load_gymnastics(path: str = "") -> Optional[Dict[str, Any]]:
    """Прочитать gymnastics.json. None — если файла нет (тогда работает запас)."""
    p = Path(path) if path else GYMNASTICS_PATH
    try:
        with p.open(encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def artic_block(sound: str, gym: Optional[Dict[str, Any]] = None
                ) -> Tuple[Dict[str, Any], List[str]]:
    """[1] Разминка: 4 названия из комплекса источника + провенанс.

    Ни одно упражнение стадии «постановка» на лист автоматизации не попадает —
    это гарантирует сам файл (`complexes[звук].sheet_4` строится из разогревочных),
    а здесь мы дополнительно проверяем поле `sounds[звук]` у каждого упражнения.
    """
    gym = gym if gym is not None else load_gymnastics()
    warns: List[str] = []
    key = sound.rstrip("'").upper() + ("ь" if sound.endswith("'") else "")
    block: Dict[str, Any] = {
        "instruction": "Повтори упражнения перед зеркалом.",
        "items": [],
        "time_note": "не больше 3 минут",
        # Строки «полный комплекс — на вкладыше» здесь больше нет: вкладыша не
        # существует — ни файла, ни генератора. Лист не имеет права обещать
        # предмет, которого нет. Вместо неё ниже печатается правда: сколько
        # упражнений в полном комплексе и где остальные.
        "note": "",
        "source": None,
    }
    if not gym:
        block["items"] = list(ARTIC_SETS_FALLBACK.get(sound, ()))
        warns.append("gymnastics.json не найден — блок [1] взят из аварийной "
                     "таблицы, провенанс не проверен")
        return block, warns

    comp = (gym.get("complexes") or {}).get(key)
    if not comp:
        block["items"] = list(ARTIC_SETS_FALLBACK.get(sound, ()))
        warns.append(f"в gymnastics.json нет комплекса для [{key}] — блок [1] "
                     f"из аварийной таблицы")
        return block, warns

    by_id = {e["id"]: e for e in gym.get("exercises", [])}
    # Рядом с названием несём КАК ДЕЛАТЬ. Домашний лист читает родитель, а он
    # упражнения не знает: «Лошадка» без подсказки для него пустое слово.
    # Данные уже собраны и выверены — `sheet_hint` и `dosage` лежат в реестре
    # у каждого упражнения; до 08-06 лист их просто выбрасывал.
    names, hints, ids = [], [], list(comp.get("sheet_4", []))
    for i, ex_id in enumerate(ids):
        ex = by_id.get(ex_id)
        if not ex:
            warns.append(f"упражнение «{ex_id}» не найдено в реестре — пропущено")
            continue
        stage = (ex.get("sounds") or {}).get(key)
        if stage == "постановка":
            warns.append(f"«{ex['name']}» для [{key}] — стадия ПОСТАНОВКИ, "
                         f"на лист автоматизации не ставится (снято)")
            continue
        names.append(comp.get("sheet_4_names", [])[i]
                     if i < len(comp.get("sheet_4_names", [])) else ex["name"])
        # На листе — только «как делать», одной строкой. Дозировку («10-15
        # щелчков») сюда не тащим: она удваивает высоту блока, а на листе уже
        # стоит канонная доза приёма («за один приём — 2-3 из 4»). Полное
        # описание с дозировкой — дело вкладыша с комплексом.
        hints.append(ex.get("sheet_hint") or "")
    block["items"] = names
    block["hints"] = hints
    src_id = comp.get("canonical_full", {}).get("source") or ""
    block["source"] = src_id or "gymnastics.json"
    block["source_title"] = comp.get("canonical_full", {}).get("title", "")

    # ПРОВЕНАНС СЧИТАЕТСЯ ПО ДАННЫМ, А НЕ УТВЕРЖДАЕТСЯ.
    # Раньше под четвёркой стояло глухое «Фомичёва М.Ф., 1989» — и это было
    # неправдой для [С] (Заборчик и Горка у Фомичёвой отсутствуют) и для [Ш]
    # (Чашечка). Теперь подпись строится из источников тех упражнений, которые
    # РЕАЛЬНО попали на лист: если хоть одно пришло из картотек практиков —
    # лист об этом говорит.
    printed = [by_id[i] for i in ids
               if i in by_id and (by_id[i].get("sounds") or {}).get(key) != "постановка"]
    from_book = [e for e in printed if src_id in (e.get("sources") or [])]
    from_kart = [e for e in printed if src_id not in (e.get("sources") or [])]
    ref = _short_ref(gym, src_id)
    if from_kart and from_book:
        block["source_ref"] = (f"{ref} — {len(from_book)} из {len(printed)}; "
                               f"остальные из картотек практиков")
    elif from_kart:
        block["source_ref"] = "картотеки практиков"
    else:
        block["source_ref"] = ref

    # Сколько упражнений в ПОЛНОМ комплексе — чтобы четвёрка не выдавала себя
    # за него. Источник: gymnastics.json, canonical_full.
    full = comp.get("canonical_full", {}).get("exercises") or []
    if full and len(full) > len(names):
        block["note"] = (f"на листе {len(names)} упражнения из {len(full)} — "
                         f"остальные у логопеда")

    # Доза — дословно из канона: «Не следует предлагать детям более двух-трёх
    # упражнений» (Фомичёва 1989). Четвёрка на листе — набор НЕДЕЛИ (7 клеток
    # отметок в шапке), поэтому говорим это прямо, а не намёком.
    if len(names) > 3:
        block["dosage"] = f"за один приём — 2-3 из {len(names)}"
    return block, warns


def _isolated_notice(isolated: Dict[str, Any], watch: FrozenSet[str],
                     gym: Optional[Dict[str, Any]], sound: str) -> List[str]:
    """То же, что _artic_name_notice, но для блока [2] — его не было.

    Блок [2] — единственная строка, где ребёнок тянет ИЗОЛИРОВАННЫЙ звук, и имя
    образа он слышит вплотную к нему. На листе [ш] канонный образ Спивак —
    «песенка змеи»: [з] и [с'] рядом с [ш] (ровно та оппозиция, ради которой
    лист и делается). Заменять источник самовольно нельзя, молчать — тоже.
    """
    out: List[str] = []
    line = str(isolated.get("line") or "")
    hits: Dict[str, Set[str]] = {}
    for token in re.findall(r"[а-яёА-ЯЁ-]+", line):
        try:
            got = corrigible_of(token) & watch
        except ValueError:
            continue
        if got:
            hits[token] = got
    if not hits:
        return out
    key = sound.rstrip("'").upper() + ("ь" if sound.endswith("'") else "")
    clean_alt = []
    for img in ((gym or {}).get("images", {}) or {}).get(key, []):
        if img.get("stage") != "автоматизация" or img.get("image") == isolated.get("image"):
            continue
        bad: Set[str] = set()
        for token in re.findall(r"[а-яёА-ЯЁ-]+", str(img.get("image", ""))):
            try:
                bad |= corrigible_of(token) & watch
            except ValueError:
                continue
        if not bad:
            clean_alt.append(f"«{img['image']}» (tier={img.get('tier')}, "
                             f"recommended={img.get('recommended')})")
    verbs = [v for v in CHILD_VERBS if not (corrigible_of(v) & watch)]
    out.append(
        "строка блока [2] содержит звуки из запрета: "
        + " · ".join(f"«{t}» ({', '.join(sorted(g))})" for t, g in sorted(hits.items()))
        + ". Фильтр к формулировке не применяется (purity_scope), но ребёнок "
          "слышит имя образа вплотную к изолированному звуку — решение за логопедом. "
        + (f"Чистые образы автоматизации в источнике: {'; '.join(clean_alt)}. "
           if clean_alt else "Чистых образов автоматизации в источнике нет. ")
        + (f"Чистые глаголы обращения: {', '.join(verbs)}." if verbs
           else "Чистого глагола обращения в каноне нет.")
    )
    return out


def _artic_name_notice(artic: Dict[str, Any], watch: FrozenSet[str],
                       gym: Optional[Dict[str, Any]], sound: str) -> List[str]:
    """Единственное место листа, где грязный звук печатается сознательно.

    Названия упражнений — канон («Лошадка», «Маляр»), заменить их «чистыми»
    синонимами нельзя, не сломав узнаваемость комплекса, поэтому фильтр к ним
    не применяется (см. purity_scope). Но молчать об этом нельзя: логопед
    должен ВИДЕТЬ, что в названиях есть звуки его ребёнка, и решить сам —
    в gymnastics.json у каждого комплекса есть `alternates`.
    """
    out: List[str] = []
    hits = []
    for name in artic.get("items", []):
        got: Set[str] = set()
        for token in re.findall(r"[а-яёА-ЯЁ-]+", name):   # имя бывает из 3 слов
            try:
                got |= corrigible_of(token) & watch
            except ValueError:
                continue
        if got:
            hits.append(f"«{name}» ({', '.join(sorted(got))})")
    if not hits:
        return out
    key = sound.rstrip("'").upper() + ("ь" if sound.endswith("'") else "")
    by_id = {e["id"]: e.get("name", e["id"]) for e in (gym or {}).get("exercises", [])}
    alt = [by_id.get(a, a) for a in
           (((gym or {}).get("complexes", {}).get(key, {}) or {}).get("alternates", []))]
    clean_alt = []
    for name in alt:
        bad: Set[str] = set()
        for token in re.findall(r"[а-яёА-ЯЁ-]+", name):
            try:
                bad |= corrigible_of(token) & watch
            except ValueError:
                continue
        if not bad:
            clean_alt.append(name)
    out.append(
        "названия упражнений блока [1] содержат звуки из запрета: "
        + " · ".join(hits)
        + ". Это канонные имена комплекса, фильтр к ним не применяется "
          "(purity_scope); ребёнок их не произносит — читает взрослый. "
        + (f"Чистые замены из alternates: {', '.join(clean_alt)}." if clean_alt
           else "Чистых замен среди alternates нет — «безымянного» комплекса "
                "канон не даёт, решение за логопедом.")
    )
    return out


def _short_ref(gym: Dict[str, Any], src_id: str) -> str:
    """«Фамилия И. О., год» из библиографии файла — подпись под блоком."""
    for s in gym.get("sources", []):
        if s.get("id") == src_id:
            m = re.match(r"\s*([А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.)", s.get("ref", ""))
            year = re.search(r"\b(19|20)\d{2}\b", s.get("ref", ""))
            if m:
                return f"{m.group(1)}, {year.group(0)}" if year else m.group(1)
    return ""


def isolated_block(sound: str, gym: Optional[Dict[str, Any]] = None
                   ) -> Tuple[Dict[str, Any], List[str]]:
    """[2] Изолированный звук — РОВНО ОДНА строка, РОВНО ОДИН игровой образ.

    Берётся образ с `recommended: true` и `stage: "автоматизация"`. Постановочные
    («заведи мотор», «дятел») отсекаются по полю stage — не по нашему вкусу.
    """
    gym = gym if gym is not None else load_gymnastics()
    warns: List[str] = []
    key = sound.rstrip("'").upper() + ("ь" if sound.endswith("'") else "")
    fallback = GAME_IMAGE_FALLBACK.get(sound, f"Повтори: {sound}-{sound}-{sound}.")
    block: Dict[str, Any] = {
        "line": fallback,
        "image": "мотор" if sound == "р" else None,
        "adult": "",
        "source": None,
    }
    if not gym:
        warns.append("gymnastics.json не найден — образ блока [2] взят из "
                     "аварийной таблицы, провенанс не проверен")
        return block, warns

    cands = [i for i in (gym.get("images") or {}).get(key, [])
             if i.get("recommended") and i.get("stage") == "автоматизация"]
    if not cands:
        warns.append(f"в gymnastics.json нет рекомендованного образа "
                     f"автоматизации для [{key}] — образ из аварийной таблицы")
        return block, warns

    img = cands[0]
    # На листе — короткая строка (правило 2: ровно одна строка). Дословная
    # формулировка источника длиннее строки А4 при 18 pt, поэтому её «длительная»
    # часть уходит в мелкую пометку взрослому, а не выбрасывается.
    verbatim = str(img.get("instruction_verbatim", ""))
    # Имя образа берём из дословной формулировки — там оно уже в нужном падеже
    # («песенку мотора»), а поле `image` хранит именительный.
    m = re.search(r"«([^»]+)»", verbatim)
    phrase = m.group(1) if m else img["image"]
    verb = (verbatim.split() or ["Спой"])[0].strip(",.«")
    if verb not in CHILD_VERBS:
        verb = "Спой"
    block["line"] = f"{verb} «{phrase}»: {img['utterance']}."
    block["image"] = img["image"]          # дословное имя образа из источника
    block["stage"] = img["stage"]
    block["adult"] = "тянуть длительно, на одном выдохе"
    block["source"] = ", ".join(img.get("sources", [])) or None
    block["verbatim"] = img.get("instruction_verbatim", "")
    return block, warns

