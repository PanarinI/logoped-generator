#
# Вывод, который стоило сделать раньше: русское словоизменение не ловится
# хвостом слова. Каждая ошибка — это грамматический брак на печатном листе для
# ребёнка, ровно того класса, который живой логопед ловил в Конспекте.
#
# Поэтому здесь действует тот же закон, что уже действует для деминутива
# («правило системно лжёт» — allow_rule_diminutive выключен) и для предложений
# («падежное согласование не генерируется — лучше беднее, чем с ошибкой»):
# ФОРМА БЕРЁТСЯ ТОЛЬКО ИЗ ВЫВЕРЕННОЙ ТАБЛИЦЫ. Нет в таблице — слово не идёт
# в игру «Посчитай 1-5», и игру берёт следующая по очереди.
#
# Чтобы вернуть игру в полную силу, нужна выверенная руками падежная таблица
# (~300 строк на 1210 слов с формой мн. ч.) — работа того же рода, что уже
# проделана с полем `plural` (309 пар) и деминутивами (108).
ALLOW_RULE_CASES = False


def _gen_sg(word: str, gender: Optional[str]) -> Optional[str]:
    """Родительный падеж ед. ч. (для «два ...»). None = правило не отвечает."""
    if word in GEN_SG_OVERRIDES:
        return GEN_SG_OVERRIDES[word]
    if not ALLOW_RULE_CASES:
        return None
    if not word:
        return None
    last = word[-1]
    if gender == "m":
        if word.endswith(_MASC_TRICKY_ENDINGS):
            return None                      # беглая гласная — только по таблице
        if last == "й":
            return word[:-1] + "я"
        if last == "ь":
            return word[:-1] + "я"
        if last in _CONS:
            return word + "а"
        return None
    if gender == "f":
        if last == "а":
            stem = word[:-1]
            return stem + ("и" if stem[-1] in "кгхжшчщ" else "ы")
        if last == "я":
            return word[:-1] + "и"
        if last == "ь":
            return word[:-1] + "и"
        return None
    if gender == "n":
        if last == "о":
            return word[:-1] + "а"
        if last == "е":
            return word[:-1] + "я"
        return None
    return None


def _gen_pl(word: str, gender: Optional[str]) -> Optional[str]:
    """Родительный падеж мн. ч. (для «пять ...»). None = правило не отвечает."""
    if word in GEN_PL_OVERRIDES:
        return GEN_PL_OVERRIDES[word]
    if not ALLOW_RULE_CASES:
        return None                          # см. комментарий у ALLOW_RULE_CASES
    if not word:
        return None
    last = word[-1]
    if gender == "m":
        if word.endswith(_MASC_TRICKY_ENDINGS):
            return None                      # беглая гласная — только по таблице
        if last in "жшчщ":
            return word + "ей"
        if last == "ь":
            return word[:-1] + "ей"
        if last == "й":
            return word[:-1] + "ев"
        if last in _CONS:
            return word + "ов"
        return None
    if gender == "f":
        if word.endswith(_FEM_TRICKY_ENDINGS):
            return None                      # своя беглая гласная — только по таблице
        if last == "а":
            stem = word[:-1]
            # беглая гласная — только в основах на -к после согласной (марка→марок)
            if len(stem) >= 2 and stem[-1] == "к" and stem[-2] in _CONS:
                fill = "е" if stem[-2] in "чщжшь" else "о"
                return stem[:-1] + fill + stem[-1]
            return stem
        if last == "ь":
            return word[:-1] + "ей"
        return None
    if gender == "n":
        return None                          # средний род — только по таблице
    return None


def _rule_diminutive(word: str, gender: Optional[str]) -> Optional[str]:
    """Грубое правило-генератор. По умолчанию НЕ используется (см. allow_rule_diminutive):
    форма помечается как непроверенная, потому что правило системно лжёт."""
    if not word:
        return None
    if gender == "m" and word[-1] in _CONS and not word.endswith(_MASC_TRICKY_ENDINGS):
        return word + "чик" if word[-1] in "рнлм" else word + "ик"
    if gender == "f" and word[-1] == "а" and word[-2] not in "кгх":
        return word[:-1] + "очка"
    return None


