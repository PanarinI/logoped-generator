def _rhyme_candidates(groups: Sequence[Dict[str, Any]], syllable: str,
                      banned: FrozenSet[str],
                      pool: Optional[Sequence[Dict[str, Any]]] = None,
                      ) -> List[Tuple[str, Dict[str, Any], bool]]:
    """Слова, у которых ПОСЛЕДНИЙ слог = целевой и он УДАРНЫЙ.

    Ищем по ВСЕМУ словарю звука (`pool`), а не только среди 12–24 слов листа.
    Канон нигде не требует, чтобы рифмующее слово стояло в словесном блоке:
    чистоговорка — свой блок. Пока искали в блоке [4], она собиралась на 11
    листах из 19 — это был наш технический потолок, а не свойство языка
    (замер 08-06).
    """
    out: List[Tuple[str, Dict[str, Any], bool]] = []
    source = ([{"items": list(pool)}] if pool is not None else groups)
    for g in source:
        for it in g["items"]:
            forms: List[Tuple[str, Optional[int], bool]] = [
                (it["word"], it["stress_syllable"], False)]
            pl = it.get("plural")
            if pl and pl != it["word"] and pl in PLURAL_STRESS:
                forms.append((pl, PLURAL_STRESS[pl], True))
            for form, stress, is_plural in forms:
                if not is_clean(form, banned, stress):
                    continue
                a = _analyze(form, stress)
                if not a.transcription.endswith(syllable):
                    continue
                if not a.syllables[-1]["stressed"]:
                    continue
                out.append((form, it, is_plural))
    out.sort(key=lambda t: t[0])
    return out


def _build_chistogovorka(groups: Sequence[Dict[str, Any]], sound: str,
                         syllables: Dict[str, Any], banned: FrozenSet[str],
                         service: Dict[str, int], rnd: random.Random,
                         derived: Dict[str, str],
                         warnings: List[str],
                         pool: Optional[Sequence[Dict[str, Any]]] = None,
                         ) -> Optional[Dict[str, Any]]:
    # Рифмуемся слогом ТОГО ЖЕ шага, что и блок [3]: «ра-ра-ра — тут гора»
    # на прямом листе и «ор-ор-ор — вот забор» на обратном. Слово обязано
    # ОКАНЧИВАТЬСЯ этим слогом, и слог обязан быть ударным.
    order: List[str] = []
    for row in syllables["rows"]:
        # рифму ищем по ЗВУЧАНИЮ — берём фонемные единицы, не печатные
        for u in row.get("units_phon", row["units"]):
            if u not in order:
                order.append(u)

    frames = [(f, kind) for f, kind in (("вот {w}", "exist"), ("тут {w}", "exist"),
                                        ("у мамы {w}", "possess"),
                                        ("у папы {w}", "possess"))
              if _template_ok(f.replace("{w}", " "), service)]
    if not frames:
        warnings.append("чистоговорка не построена: служебные слова не прошли фильтр")
        return None

    for syl in order:
        cands = _rhyme_candidates(groups, syl, banned, pool)
        pairs = [(form, item, is_pl, f, kind)
                 for form, item, is_pl in cands
                 for f, kind in frames if _frame_ok(item, kind)]
        if not pairs:
            continue
        form, item, is_plural, frame, _kind = pairs[rnd.randrange(len(pairs))]
        if is_plural:
            derived[form] = item["word"]
        phrase = frame.format(w=form)
        syl_out = ortho(syl)
        text = f"{syl_out}-{syl_out}-{syl_out} — {phrase}."
        return {
            "instruction": "Повтори, прочитай чистоговорку.",
            "syllable": syl_out,
            "syllable_phon": syl,
            "rhyme_word": form,
            # ударение формы — нужно вёрстке (канон требует ставить его в
            # неочевидных словах) и проверке рифмы
            "rhyme_stress": (PLURAL_STRESS[form] if is_plural
                             else item["stress_syllable"]),
            "text": text[0].upper() + text[1:],
        }

    warnings.append(
        "чистоговорка не построена: в блоке [4] нет слова с УДАРНЫМ последним "
        f"слогом на [{sound}]+гласная (рифмовать не на что; расширьте словарь "
        f"словами типа «гора», «ведро», «комары»)"
    )
    return None


