def _gen_sg(word: str, gender: Optional[str]) -> Optional[str]:
    """Родительный падеж ед. ч. (для «два ...»). None = правило не отвечает."""
    if word in GEN_SG_OVERRIDES:
        return GEN_SG_OVERRIDES[word]
    if not ALLOW_RULE_CASES:
        return None
    if not word:
        return None
    last = word[-1]
    if gender == "m":
        if word.endswith(_MASC_TRICKY_ENDINGS):
            return None                      # беглая гласная — только по таблице
        if last == "й":
            return word[:-1] + "я"
        if last == "ь":
            return word[:-1] + "я"
        if last in _CONS:
            return word + "а"
        return None
    if gender == "f":
        if last == "а":
            stem = word[:-1]
            return stem + ("и" if stem[-1] in "кгхжшчщ" else "ы")
        if last == "я":
            return word[:-1] + "и"
        if last == "ь":
            return word[:-1] + "и"
        return None
    if gender == "n":
        if last == "о":
            return word[:-1] + "а"
        if last == "е":
            return word[:-1] + "я"
        return None
    return None


