def translit(word):
    return "".join(TRANSLIT.get(ch, ch) for ch in word.lower())


def letter_check(word):
    """Независимая от движка побуквенная проверка."""
    w = word.lower()
    bad = sorted(set(w) & BAD_LETTERS)
    if bad:
        return "буквы %s" % bad
    for i, ch in enumerate(w):
        if ch in IOT_LETTERS:
            if i == 0:
                return "йотация в начале: %s" % ch
            if w[i - 1] in VOWEL_LETTERS or w[i - 1] in "ьъ":
                return "йотация после гласной/ь: %s" % ch
    return None


def main():
    errors, records, seen = [], [], set()

    for (word, stress, mtype, gender, sem, fam, age, ambig,
         plural, dim_blocked, note) in D:
        if word in seen:
            errors.append("%s: дубль" % word)
        seen.add(word)

        # (1) движок: транскрипция из написания, нейтральность, тип Марковой
        a = phonetics.analyze(word, stress)
        if not a.is_neutral or a.problem_phonemes:
            errors.append("%s: движок нашёл корригируемые %s"
                          % (word, sorted(a.problem_phonemes)))
        if a.markova_v1 != mtype:
            errors.append("%s: ручной тип %s != движок %s (%s)"
                          % (word, mtype, a.markova_v1, a.markova_label))

        # (2) независимая побуквенная проверка
        lp = letter_check(word)
        if lp:
            errors.append("%s: %s" % (word, lp))

        # (3) форма мн. ч. — её ребёнок тоже произносит
        if plural:
            # ударение в форме мн.ч. не размечаем: редукция гласных не может
            # породить корригируемую ФОНЕМУ, а фильтр смотрит только на них
            pa = phonetics.analyze(plural, 1)
            if not pa.is_neutral:
                errors.append("%s: мн.ч. '%s' [%s] содержит %s"
                              % (word, plural, pa.transcription,
                                 sorted(pa.problem_phonemes)))
            lp2 = letter_check(plural)
            if lp2:
                errors.append("%s: мн.ч. '%s' — %s" % (word, plural, lp2))

        wid = translit(word)
        if any(r["id"] == wid for r in records):
            errors.append("%s: коллизия id '%s'" % (word, wid))

        records.append({
            "id": wid,
            "word": word,
            "transcription": a.transcription,
            "stress_syllable": stress,
            "pos": "noun",
            "semantic_category": sem,
            "familiarity": fam,
            "age_min": age,
            "sensitive": False,
            "ambiguous": ambig,
            "plural": plural,
            "gender": gender,
            "imageable": sem != "абстрактное",
            "markova_v1_guess": a.markova_v1,
            "other_correctable": [],
            "note": note,
            # два поля сверх схемы задачи 2:
            "neutral": True,
            "diminutive_blocked_by": dim_blocked,
        })

    if errors:
        print("ОШИБКИ (%d):" % len(errors))
        for e in errors:
            print("  -", e)
        return 1

    with open(OUT, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("OK, записано слов:", len(records))

    ana = [phonetics.analyze(r["word"], r["stress_syllable"]) for r in records]
    print("типы Марковой:", dict(sorted(Counter(a.markova_v1 for a in ana).items())))
    print("слогов:", dict(sorted(Counter(a.n_syllables for a in ana).items())))
    print("знакомость (3/2/1):", dict(sorted(
        Counter(r["familiarity"] for r in records).items(), reverse=True)))
    print("род:", dict(Counter(r["gender"] for r in records)))
    print("одушевлённых:", sum(1 for r in records if r["word"] in ANIMATE))
    print("с чистой формой мн.ч.:", sum(1 for r in records if r["plural"]))
    print("с чистой уменьшительной формой:", 0)
    print("полей в записи:", len(records[0]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
