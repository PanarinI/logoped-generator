VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")
# оппозиционные Ш звуки + Ц: в словаре [ш] их не должно быть НИ ОДНОГО
BANNED_SOUNDS = set("сзжчщц")


def positions(tr):
    """Позиции [ш] в транскрипции. Ш всегда твёрдый — апострофа не бывает."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "ш":
            continue
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:
            prev = tr[i - 2] if i > 1 else None
        nxt = tr[i + 1] if i + 1 < n else None
        if nxt == SOFT:                      # ШНь, ШЛь — мягкий следующий согласный
            nxt = tr[i + 1]
        if i == 0:
            res.append("начало слова" if (nxt in VOWELS) else "стечение в начале (Ш первым)")
        elif nxt is None:
            res.append("стечение в конце (Ш вторым)" if prev in CONS else "конец слова")
        elif prev in CONS:
            res.append("стечение в середине (Ш вторым)")
        elif nxt in CONS:
            res.append("стечение в середине (Ш первым)")
        else:
            res.append("середина между гласными")
    return res


def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "ш":
            j = i + 1
            if j < len(tr) and tr[j] in VOWELS:
                return "Ш" + tr[j].upper()
    return "Ш+согласный/конец"


