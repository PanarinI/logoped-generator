VOWELS = set("аоуыэеёюяи")
SOFT = "'"
CONS = set("бвгджзйклмнпрстфхцчшщ")
TARGET = "з'"
OPPOSITION = ("ш", "ч", "щ", "с", "с'", "ц")     # оппозиционные звуки цели
HUSHING = ("ш", "ж", "щ", "ч")                    # шипящие
WHISTLING = ("с", "с'", "з", "з'", "ц")           # свистящие
BACKLINGUAL = ("к", "к'", "г", "г'", "х", "х'")   # заднеязычные


def _soft_at(tr, i):
    return i + 1 < len(tr) and tr[i + 1] == SOFT


def positions(tr):
    """Позиции МЯГКОГО з' в транскрипции."""
    res = []
    n = len(tr)
    for i, ch in enumerate(tr):
        if ch != "з" or not _soft_at(tr, i):
            continue
        prev = tr[i - 1] if i > 0 else None
        if prev == SOFT:                       # апостроф принадлежит предыдущей согласной
            prev = tr[i - 2] if i > 1 else None
        j = i + 2                              # пропускаем сам апостроф
        nxt = tr[j] if j < n else None
        if i == 0:
            res.append("начало слова")
        elif nxt is None:
            res.append("конец слова")          # для з' невозможно (оглушение) — страховка
        elif prev in CONS:
            res.append("стечение (з' вторым)")
        elif nxt in CONS:
            res.append("стечение (з' первым)")
        else:
            res.append("середина между гласными")
    return res


def hard_z_present(tr):
    """Есть ли в слове ТВЁРДЫЙ [з] — такое слово в картотеку не годится."""
    for i, ch in enumerate(tr):
        if ch == "з" and not _soft_at(tr, i):
            return True
    return False


def vowel_after(tr):
    for i, ch in enumerate(tr):
        if ch == "з" and _soft_at(tr, i):
            j = i + 2
            if j < len(tr) and tr[j] in VOWELS:
                return "Зь+" + tr[j].upper()
    return "Зь+согласный"


