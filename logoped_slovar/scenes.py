# -*- coding: utf-8 -*-
"""
scenes.py — ФОН слоговой дорожки: сюжетная сцена, которую выбирает логопед.

Откуда взялось
─────────────────────────────────────────────────────────────────────
Дословная строка запроса Ольги Субботиной (`ГОЛОСА.md`): «Алгоритм должен
уметь менять **фон**, звук, слог в зависимости от запроса». Звук и слог
генератор менял с самого начала, фон — единственный параметр запроса, к
которому не подходили ни разу. На её фото 1 тропа со слогами лежит на
ПОДВОДНОЙ сцене: это не украшение, а сюжет, в котором ребёнок идёт.

Решение автора 2026-08-09: фон — не одна картинка, а ВЫБОР из нескольких.
Логопед печатает под ребёнка: одному море, другому лес.

Чем фон отличается от речевого материала — и почему это важно
─────────────────────────────────────────────────────────────────────
Фильтр чистоты по профилю ребёнка сюда НЕ применяется, и это не поблажка:
ребёнок сцену не НАЗЫВАЕТ, он в ней находится. Называет он только слоги в
кружках. Ровно та же граница записана у лабиринта («ребёнок картинку не
называет, а узнаёт») и в `content['purity_scope']`.
Отсюда прямое следствие: в сцене не должно быть предмета, который просится
быть названным — крупного, одиночного, в центре. Сцена идёт по краям и
фоном, мелко и много, чтобы читаться как среда, а не как задание.

Ремесло печати (из-за чего именно такие числа)
─────────────────────────────────────────────────────────────────────
  • сцена рисуется ТОНКО (0.7–0.9) и БЛЕДНО (opacity ~0.3): на ч/б принтере
    жирная фоновая линия спорит с кружком, и слог перестаёт читаться;
  • кружки уже залиты белым (`fill="#fff"`), поэтому сцена может идти
    насквозь — слоги «пробивают» её насквозь, как на образце Ольги;
  • ни одной заливки серым: серое пятно на дешёвом принтере станет грязью.
"""

from __future__ import annotations

import math
from typing import Callable, Dict, List, Tuple

__all__ = ["scene_svg", "SCENES", "SCENE_LABELS"]

SCENE_LABELS: Dict[str, str] = {
    "": "без фона",
    "море": "море",
    "лес": "лес",
    "небо": "небо",
    "дорога": "дорога",
}

# Умолчание по ПЕРСОНАЖУ, а не по звуку: фон и герой должны жить в одном
# мире. Замер глазами 08-09: море + мотор дало машину под водой — ребёнок
# это видит раньше взрослого. Логопед умолчание переопределяет: выбор за ним,
# наш долг — не подсунуть нелепицу по умолчанию.
DEFAULT_SCENE: Dict[str, str] = {
    "мотор": "дорога", "моторчик": "дорога",
    "самолёт": "небо", "самолётик": "небо",
    "комарик": "лес", "змея": "лес", "жук": "лес",
    "насос": "", "насосик": "", "щётка": "",
}


def _sea(w: float, h: float) -> List[str]:
    """Море. Живёт в четырёх свободных зонах листа: верхняя полоса, нижняя,
    и две кромки по краям шириной ~7 мм. Водоросли для кромок идеальны — они
    сами по себе узкие и высокие."""
    p: List[str] = []
    # поверхность воды — пять волн, чтобы читалась именно вода, а не черта
    for y in (3.0, 7.0, 11.0, 15.0, 19.0):
        d = [f"M0 {y:.1f}"]
        step, x, up = 13.0, 0.0, True
        while x < w:
            d.append(f"q {step/2:.1f} {-3.0 if up else 3.0:.1f} {step:.1f} 0")
            x += step
            up = not up
        p.append(f'<path d="{" ".join(d)}"/>')
    # водоросли по обеим кромкам, от дна вверх на разную высоту
    for x, top in ((3.0, h * 0.34), (6.5, h * 0.52), (w - 3.0, h * 0.30),
                   (w - 6.5, h * 0.55)):
        seg, y, d = 13.0, h - 7.0, [f"M{x:.1f} {h-7:.1f}"]
        bend = 5.0
        while y > top:
            d.append(f"q {bend:.1f} {-seg/2:.1f} 0 {-seg:.1f}")
            bend = -bend
            y -= seg
        p.append(f'<path d="{" ".join(d)}"/>')
    # пузырьки — вертикальными цепочками в тех же кромках
    for x0 in (4.0, w - 4.0):
        for i in range(7):
            y = h * 0.18 + i * (h * 0.62) / 7
            p.append(f'<circle cx="{x0 + (1.8 if i % 2 else -1.8):.1f}" '
                     f'cy="{y:.1f}" r="{1.5 + (i % 3) * 0.6:.1f}"/>')
    # дно, камни и ракушки
    p.append(f'<path d="M0 {h-6:.1f} Q {w*0.22:.1f} {h-12:.1f} {w*0.44:.1f} {h-7:.1f} '
             f'T {w:.1f} {h-8:.1f}"/>')
    for x in (w * 0.14, w * 0.38, w * 0.62, w * 0.86):
        p.append(f'<path d="M{x:.1f} {h-7:.1f} a 7 6 0 0 1 14 0 z"/>')
        p.append(f'<path d="M{x+3:.1f} {h-7:.1f} l 2 -4.5 M{x+7:.1f} {h-7:.1f} l 0 -5.5 '
                 f'M{x+11:.1f} {h-7:.1f} l -2 -4.5"/>')
    for x in (w * 0.27, w * 0.72):
        p.append(f'<path d="M{x:.1f} {h-7:.1f} a 5 4 0 0 1 10 0 z"/>')
    return p


def _forest(w: float, h: float) -> List[str]:
    p: List[str] = []
    # ёлки по левому и правому краю — узкой полосой, чтобы не лезть под слоги
    for x in (8.0, 20.0, w - 10.0, w - 22.0):
        for k in range(3):
            top = 30 + k * (h - 70) / 3
            p.append(f'<path d="M{x:.1f} {top:.1f} l -7 14 l 4 0 l -6 12 l 18 0 '
                     f'l -6 -12 l 4 0 z"/>')
            p.append(f'<path d="M{x:.1f} {top+26:.1f} l 0 6"/>')
    # трава по низу
    d = []
    x = 0.0
    while x < w:
        d.append(f"M{x:.1f} {h-4:.1f} q 2 -6 4 -8 M{x+3:.1f} {h-4:.1f} q 0 -5 2 -7")
        x += 9
    p.append(f'<path d="{" ".join(d)}"/>')
    # грибы и облака
    for x in (w * 0.3, w * 0.55, w * 0.75):
        p.append(f'<path d="M{x:.1f} {h-6:.1f} l 0 -5 M{x-4:.1f} {h-11:.1f} '
                 f'a 4.5 4 0 0 1 9 0 z"/>')
    for cx, cy in ((26, 12), (w * 0.5, 8), (w - 30, 14)):
        p.append(f'<path d="M{cx-14:.1f} {cy+4:.1f} a 6 6 0 0 1 6 -6 '
                 f'a 8 8 0 0 1 15 1 a 5 5 0 0 1 1 5 z"/>')
    return p


def _sky(w: float, h: float) -> List[str]:
    p: List[str] = []
    # солнце в углу
    p.append('<circle cx="20" cy="16" r="9"/>')
    for i in range(8):
        a = i * math.pi / 4
        p.append(f'<path d="M{20 + 12*math.cos(a):.1f} {16 + 12*math.sin(a):.1f} '
                 f'L{20 + 16*math.cos(a):.1f} {16 + 16*math.sin(a):.1f}"/>')
    # облака по краям и между рядами
    for cx, cy in ((w * 0.55, 10), (w - 26, 22), (16, h * 0.45),
                   (w - 18, h * 0.62), (w * 0.5, h - 16)):
        p.append(f'<path d="M{cx-16:.1f} {cy+5:.1f} a 7 7 0 0 1 7 -7 '
                 f'a 9 9 0 0 1 17 1 a 6 6 0 0 1 1 6 z"/>')
    # птички — «галочки», самый дешёвый узнаваемый знак
    for x, y in ((w * 0.3, 20), (w * 0.36, 15), (w * 0.42, 22),
                 (w * 0.7, h * 0.3), (w * 0.76, h * 0.34)):
        p.append(f'<path d="M{x-5:.1f} {y:.1f} q 2.5 -3.5 5 0 q 2.5 -3.5 5 0"/>')
    return p


def _road(w: float, h: float) -> List[str]:
    """Дорога — мир мотора. Полотно по низу, дома по кромкам, облака сверху."""
    p: List[str] = []
    # обочина и разметка
    p.append(f'<path d="M0 {h-14:.1f} L{w:.1f} {h-14:.1f}"/>')
    p.append(f'<path d="M0 {h-3:.1f} L{w:.1f} {h-3:.1f}"/>')
    x = 4.0
    while x < w:
        p.append(f'<path d="M{x:.1f} {h-8.5:.1f} l 9 0"/>')
        x += 18.0
    # домики по обеим кромкам, на разной высоте
    for x, y in ((2.0, h * 0.22), (2.0, h * 0.52), (2.0, h * 0.80),
                 (w - 16.0, h * 0.34), (w - 16.0, h * 0.64)):
        p.append(f'<path d="M{x:.1f} {y:.1f} l 0 -9 l 7 -6 l 7 6 l 0 9 z"/>')
        p.append(f'<path d="M{x+5:.1f} {y:.1f} l 0 -5 l 4 0 l 0 5"/>')
    # фонари вдоль дороги
    for x in (w * 0.2, w * 0.5, w * 0.8):
        p.append(f'<path d="M{x:.1f} {h-14:.1f} l 0 -13 q 0 -4 5 -4"/>')
        p.append(f'<circle cx="{x+6:.1f}" cy="{h-31:.1f}" r="2.2"/>')
    # облака
    for cx, cy in ((28, 10), (w * 0.55, 7), (w - 34, 13)):
        p.append(f'<path d="M{cx-14:.1f} {cy+4:.1f} a 6 6 0 0 1 6 -6 '
                 f'a 8 8 0 0 1 15 1 a 5 5 0 0 1 1 5 z"/>')
    return p


SCENES: Dict[str, Callable[[float, float], List[str]]] = {
    "море": _sea,
    "лес": _forest,
    "небо": _sky,
    "дорога": _road,
}


def scene_svg(name: str, w: float, h: float,
              stroke: float = 0.8, opacity: float = 0.30) -> str:
    """Слой сцены для вставки ПЕРВЫМ в <svg> дорожки (под тропу и кружки).

    Пустая строка — законный ответ: «без фона» это выбор логопеда, а не
    отсутствие возможности."""
    fn = SCENES.get(name or "")
    if not fn:
        return ""
    body = "".join(fn(w, h))
    return (f'<g fill="none" stroke="#000" stroke-width="{stroke}" '
            f'stroke-linecap="round" stroke-linejoin="round" '
            f'opacity="{opacity}">{body}</g>')
