VOWEL_SOUNDS = set("аоуыэи")
SOFT = "'"


def skeleton(tr):
    """Согласный скелет транскрипции: только согласные с пометой мягкости."""
    out = []
    i = 0
    while i < len(tr):
        ch = tr[i]
        if ch in VOWEL_SOUNDS or ch == SOFT or ch == "-":
            i += 1
            continue
        out.append(ch + (SOFT if (i + 1 < len(tr) and tr[i + 1] == SOFT) else ""))
        i += 1
    return out


def engine_skeleton(a):
    return [p.key for p in a.phonemes if p.is_consonant]


