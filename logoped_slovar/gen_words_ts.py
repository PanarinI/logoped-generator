# Отбракованы вторым разбором: «холодец» — масса, не один предмет; «мудрец» — редкое (familiarity 1).
DROP = {"холодец", "мудрец"}
NOT_COUNTABLE = set()

_PH_RE = re.compile(r"[а-яё]'?")


def other_correctable(tr):
    """Прочие корригируемые звуки ПО РУЧНОЙ транскрипции (цель не входит)."""
    out = []
    for ph in _PH_RE.findall(tr):
        if ph in P.CORRIGIBLE and ph != TARGET and ph not in out:
            out.append(ph)
    return sorted(out)


