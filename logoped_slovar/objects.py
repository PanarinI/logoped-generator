def has_object(word: str) -> bool:
    return word.lower().strip() in OBJECTS


def object_svg(word: str, width_mm: float = 24.0,
               stroke: float = 2.2) -> str:
    """Готовый <svg> предмета. Пусто, если рисунка нет — вызывающий сам решает,
    ставить ли заглушку: молча подсовывать чужой предмет нельзя."""
    body = OBJECTS.get(word.lower().strip())
    if not body:
        return ""
    h = width_mm * 0.85
    return (f'<svg viewBox="0 0 100 85" width="{width_mm}mm" height="{h}mm" '
            f'fill="none" stroke="#000" stroke-width="{stroke}" '
            f'stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
